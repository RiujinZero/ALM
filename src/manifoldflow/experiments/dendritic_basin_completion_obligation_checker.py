"""Formal paired worlds and an independent byte-level completion checker.

The worlds isolate a long-range binding obligation.  Each member of a pair has
the same named entity, role and value vocabulary, final request, lexical
multiset, and long final interruption.  Only the corrected role-to-value
binding differs.  Consequently, a locally identical suffix cannot identify the
right completion.

The checker is deliberately downstream of generation.  Its complete input is a
``CompletionObligationWorld`` record and generated bytes; it has no learner,
potential, trie, likelihood, or score input.  Exact acceptance requires all
three correct clauses in any order, followed by exactly ``DONE\n`` and nothing
else.
"""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from itertools import combinations, permutations

ROLES = ("alpha", "beta", "gamma")
VALUES = ("red", "blue", "green")
TERMINATOR = b"DONE\n"
MINIMUM_INTERRUPTION_BYTES = 512

_CLAIM_PATTERN = re.compile(
    rb"ENTITY ([A-Za-z][A-Za-z0-9_-]*) ROLE ([A-Za-z][A-Za-z0-9_-]*) "
    rb"VALUE ([A-Za-z][A-Za-z0-9_-]*)\n"
)
_LEXICAL_PATTERN = re.compile(rb"[A-Za-z0-9]+")
_INTERRUPTION_MATERIAL = (
    b"Neutral intermission note: quartz lanterns drift beside quiet canals; "
    b"this material carries no correction, assignment, or binding update.\n"
)


@dataclass(frozen=True)
class CompletionObligationWorld:
    """One learner-facing prompt plus generator-owned evaluation metadata."""

    world_id: str
    pair_id: str
    counterpart_world_id: str
    entity: str
    prompt: bytes
    common_suffix: bytes
    interruption: bytes
    final_resume_request: bytes
    required_role_to_value: tuple[tuple[str, str], ...]
    accepted_full_completions: tuple[bytes, ...]
    consistency_accepted_sequences: tuple[bytes, ...]
    marginal_unbound_sequences: tuple[bytes, ...]

    @property
    def required_mapping(self) -> dict[str, str]:
        """Return the required binding as a fresh, caller-owned mapping."""

        return dict(self.required_role_to_value)


@dataclass(frozen=True)
class CompletionObligationPair:
    """Two worlds that differ only in their corrected binding history."""

    pair_id: str
    world_a: CompletionObligationWorld
    world_b: CompletionObligationWorld

    @property
    def worlds(self) -> tuple[CompletionObligationWorld, ...]:
        return (self.world_a, self.world_b)

    def counterpart(
        self, world: CompletionObligationWorld | str
    ) -> CompletionObligationWorld:
        """Return the other member, rejecting records from another pair."""

        world_id = world if isinstance(world, str) else world.world_id
        if world_id == self.world_a.world_id:
            return self.world_b
        if world_id == self.world_b.world_id:
            return self.world_a
        raise ValueError(f"world {world_id!r} is not a member of {self.pair_id!r}")


@dataclass(frozen=True)
class CompletionClaim:
    """One syntactically valid claim found before the first terminator."""

    line_index: int
    raw: bytes
    entity: str
    role: str
    value: str


@dataclass(frozen=True)
class UnsupportedClaim:
    """A claim outside the entity, role, or value vocabulary of the world."""

    claim: CompletionClaim
    reasons: tuple[str, ...]


@dataclass(frozen=True)
class ConflictingRepeat:
    """Distinct values asserted for one supported role before termination."""

    role: str
    values: tuple[str, ...]
    line_indices: tuple[int, ...]


@dataclass(frozen=True)
class CompletionCheck:
    """Semantic diagnostics plus exact byte acceptance for one world."""

    world_id: str
    generated: bytes
    claims: tuple[CompletionClaim, ...]
    completed_obligations: tuple[str, ...]
    missing_obligations: tuple[str, ...]
    wrong_claims: tuple[CompletionClaim, ...]
    unsupported_claims: tuple[UnsupportedClaim, ...]
    conflicting_repeats: tuple[ConflictingRepeat, ...]
    unparsed_content: tuple[bytes, ...]
    explicit_termination: bool
    termination_count: int
    terminated_early: bool
    trailing_content: bool
    trailing_bytes: bytes
    exact_accepted: bool


@dataclass(frozen=True)
class CrossedCompletionCheck:
    """Evaluate two generated byte strings on matched and crossed worlds."""

    pair_id: str
    a_on_a: CompletionCheck
    b_on_b: CompletionCheck
    a_on_b: CompletionCheck
    b_on_a: CompletionCheck
    matched_exact_count: int
    crossed_exact_count: int
    matched_pair_accepted: bool
    crossed_pair_accepted: bool
    binding_sensitive_pair_accepted: bool


def _safe_symbol(value: str, *, label: str) -> str:
    if not isinstance(value, str):
        raise TypeError(f"{label} must be a string")
    try:
        encoded = value.encode("ascii")
    except UnicodeEncodeError as exc:
        raise ValueError(f"{label} must be ASCII") from exc
    if re.fullmatch(rb"[A-Za-z][A-Za-z0-9_-]*", encoded) is None:
        raise ValueError(f"{label} is not a valid output symbol: {value!r}")
    return value


def _ordered_binding(
    role_to_value: Mapping[str, str] | Sequence[tuple[str, str]],
) -> tuple[tuple[str, str], ...]:
    mapping = dict(role_to_value)
    if set(mapping) != set(ROLES):
        raise ValueError(f"binding must have exactly the roles {ROLES!r}")
    if len(mapping) != len(ROLES):
        raise ValueError("binding contains repeated roles")
    values = tuple(mapping[role] for role in ROLES)
    if set(values) != set(VALUES) or len(set(values)) != len(VALUES):
        raise ValueError(f"binding values must be a permutation of {VALUES!r}")
    for role, value in zip(ROLES, values, strict=True):
        _safe_symbol(role, label="role")
        _safe_symbol(value, label="value")
    return tuple(zip(ROLES, values, strict=True))


def render_claim(entity: str, role: str, value: str) -> bytes:
    """Render one clause in the checker's strict byte grammar."""

    entity = _safe_symbol(entity, label="entity")
    role = _safe_symbol(role, label="role")
    value = _safe_symbol(value, label="value")
    return f"ENTITY {entity} ROLE {role} VALUE {value}\n".encode("ascii")


def render_full_completions(
    entity: str,
    role_to_value: Mapping[str, str] | Sequence[tuple[str, str]],
) -> tuple[bytes, ...]:
    """Return all six clause-order variants for one complete binding."""

    binding = dict(_ordered_binding(role_to_value))
    return tuple(
        b"".join(render_claim(entity, role, binding[role]) for role in order)
        + TERMINATOR
        for order in permutations(ROLES)
    )


def render_consistency_accepted_sequences(
    entity: str,
    role_to_value: Mapping[str, str] | Sequence[tuple[str, str]],
) -> tuple[bytes, ...]:
    """Return every ordered true subset, including immediate termination.

    There are sixteen sequences: one empty subset, three singleton orders, six
    two-clause orders, and six full orders.  This is the exact ceiling for a
    consistency-only objective that does not require obligation completion.
    """

    binding = dict(_ordered_binding(role_to_value))
    outputs: list[bytes] = []
    for size in range(len(ROLES) + 1):
        for subset in combinations(ROLES, size):
            for order in permutations(subset):
                outputs.append(
                    b"".join(
                        render_claim(entity, role, binding[role]) for role in order
                    )
                    + TERMINATOR
                )
    return tuple(outputs)


def render_marginal_unbound_sequences(entity: str) -> tuple[bytes, ...]:
    """Return all bindings and clause orders with the correct marginals.

    The thirty-six sequences are the Cartesian product of all ``3!``
    role-to-value assignments and all ``3!`` output orders.  They preserve the
    role and value marginals while deliberately making binding uninformative.
    """

    outputs: list[bytes] = []
    for assigned_values in permutations(VALUES):
        binding = dict(zip(ROLES, assigned_values, strict=True))
        outputs.extend(render_full_completions(entity, binding))
    return tuple(outputs)


def lexical_multiset(payload: bytes) -> Counter[bytes]:
    """Return a case-normalized ASCII lexical multiset for pair auditing."""

    if not isinstance(payload, bytes):
        raise TypeError("payload must be bytes")
    return Counter(token.lower() for token in _LEXICAL_PATTERN.findall(payload))


def _make_interruption(interruption_bytes: int) -> bytes:
    if isinstance(interruption_bytes, bool) or not isinstance(interruption_bytes, int):
        raise TypeError("interruption_bytes must be an integer")
    if interruption_bytes < MINIMUM_INTERRUPTION_BYTES:
        raise ValueError(
            f"interruption_bytes must be at least {MINIMUM_INTERRUPTION_BYTES}"
        )
    repeats = (
        interruption_bytes + len(_INTERRUPTION_MATERIAL) - 1
    ) // len(_INTERRUPTION_MATERIAL)
    return (_INTERRUPTION_MATERIAL * repeats)[:interruption_bytes]


def _render_early_evidence(
    entity: str,
    anchor: Sequence[tuple[str, str]],
    corrected: Sequence[tuple[str, str]],
) -> bytes:
    lines = [
        b"MEMORY BEGINS\n",
        f"All records below concern the named entity {entity}.\n".encode("ascii"),
    ]
    lines.extend(
        f"ANCHOR ENTITY {entity} ROLE {role} VALUE {value}\n".encode("ascii")
        for role, value in anchor
    )
    lines.extend(
        f"CORRECTION ENTITY {entity} ROLE {role} VALUE {value}\n".encode("ascii")
        for role, value in corrected
    )
    lines.extend(
        (
            b"Each CORRECTION replaces the ANCHOR for the same role.\n",
            b"The three CORRECTION records are the current binding.\n",
            b"MEMORY ENDS\n",
        )
    )
    return b"".join(lines)


def _world(
    *,
    pair_id: str,
    side: str,
    counterpart_side: str,
    entity: str,
    anchor: tuple[tuple[str, str], ...],
    corrected: tuple[tuple[str, str], ...],
    interruption: bytes,
) -> CompletionObligationWorld:
    world_id = f"{pair_id}-{side}"
    counterpart_world_id = f"{pair_id}-{counterpart_side}"
    final_resume_request = (
        f"FINAL RESUME REQUEST: For entity {entity}, state every current binding "
        f"exactly once as ENTITY {entity} ROLE role VALUE value, in any order. "
        "Then emit exactly DONE on its own line and stop.\nASSISTANT:\n"
    ).encode("ascii")
    common_suffix = (
        b"BEGIN IDENTICAL INTERRUPTION\n"
        + interruption
        + b"\nEND IDENTICAL INTERRUPTION\n"
        + final_resume_request
    )
    prompt = _render_early_evidence(entity, anchor, corrected) + common_suffix
    return CompletionObligationWorld(
        world_id=world_id,
        pair_id=pair_id,
        counterpart_world_id=counterpart_world_id,
        entity=entity,
        prompt=prompt,
        common_suffix=common_suffix,
        interruption=interruption,
        final_resume_request=final_resume_request,
        required_role_to_value=corrected,
        accepted_full_completions=render_full_completions(entity, corrected),
        consistency_accepted_sequences=render_consistency_accepted_sequences(
            entity, corrected
        ),
        marginal_unbound_sequences=render_marginal_unbound_sequences(entity),
    )


def build_completion_obligation_pair(
    pair_index: int = 0,
    *,
    interruption_bytes: int = 768,
) -> CompletionObligationPair:
    """Build one deterministic pair with mutually deranged current bindings."""

    if isinstance(pair_index, bool) or not isinstance(pair_index, int):
        raise TypeError("pair_index must be an integer")
    if pair_index < 0:
        raise ValueError("pair_index must be non-negative")
    pair_id = f"completion-obligation-pair-{pair_index:06d}"
    entity = f"Nera{pair_index:06d}"
    offset = pair_index % len(VALUES)
    a_values = tuple(VALUES[(offset + index) % len(VALUES)] for index in range(3))
    b_values = tuple(
        VALUES[(offset + index + 1) % len(VALUES)] for index in range(3)
    )
    binding_a = tuple(zip(ROLES, a_values, strict=True))
    binding_b = tuple(zip(ROLES, b_values, strict=True))
    interruption = _make_interruption(interruption_bytes)
    world_a = _world(
        pair_id=pair_id,
        side="a",
        counterpart_side="b",
        entity=entity,
        anchor=binding_b,
        corrected=binding_a,
        interruption=interruption,
    )
    world_b = _world(
        pair_id=pair_id,
        side="b",
        counterpart_side="a",
        entity=entity,
        anchor=binding_a,
        corrected=binding_b,
        interruption=interruption,
    )
    pair = CompletionObligationPair(pair_id, world_a, world_b)
    validate_completion_obligation_pair(pair)
    return pair


def build_completion_obligation_pairs(
    count: int,
    *,
    start_index: int = 0,
    interruption_bytes: int = 768,
) -> tuple[CompletionObligationPair, ...]:
    """Build a deterministic contiguous collection of formal pairs."""

    if isinstance(count, bool) or not isinstance(count, int):
        raise TypeError("count must be an integer")
    if count < 0:
        raise ValueError("count must be non-negative")
    if isinstance(start_index, bool) or not isinstance(start_index, int):
        raise TypeError("start_index must be an integer")
    if start_index < 0:
        raise ValueError("start_index must be non-negative")
    return tuple(
        build_completion_obligation_pair(
            index, interruption_bytes=interruption_bytes
        )
        for index in range(start_index, start_index + count)
    )


def validate_completion_obligation_pair(pair: CompletionObligationPair) -> None:
    """Raise if the paired-world controls no longer hold exactly."""

    a, b = pair.worlds
    if a.pair_id != pair.pair_id or b.pair_id != pair.pair_id:
        raise ValueError("world pair IDs do not match their container")
    if a.counterpart_world_id != b.world_id or b.counterpart_world_id != a.world_id:
        raise ValueError("counterpart world IDs are not reciprocal")
    if a.entity != b.entity:
        raise ValueError("paired worlds must name the same entity")
    if a.prompt == b.prompt:
        raise ValueError("paired prompts must carry different corrected bindings")
    if a.common_suffix != b.common_suffix:
        raise ValueError("paired common suffixes differ")
    if a.interruption != b.interruption:
        raise ValueError("paired interruptions differ")
    if len(a.interruption) < MINIMUM_INTERRUPTION_BYTES:
        raise ValueError("paired interruption is too short")
    if a.final_resume_request != b.final_resume_request:
        raise ValueError("paired final resume requests differ")
    if not a.prompt.endswith(a.common_suffix) or not b.prompt.endswith(b.common_suffix):
        raise ValueError("common suffix is not an exact prompt suffix")
    if lexical_multiset(a.prompt) != lexical_multiset(b.prompt):
        raise ValueError("paired prompts do not have the same lexical multiset")
    binding_a = _ordered_binding(a.required_role_to_value)
    binding_b = _ordered_binding(b.required_role_to_value)
    if any(
        value_a == value_b
        for (_, value_a), (_, value_b) in zip(binding_a, binding_b, strict=True)
    ):
        raise ValueError("paired corrected bindings are not mutually deranged")
    for world in pair.worlds:
        if world.accepted_full_completions != render_full_completions(
            world.entity, world.required_role_to_value
        ):
            raise ValueError("accepted full-completion set is inconsistent")
        if world.consistency_accepted_sequences != (
            render_consistency_accepted_sequences(
                world.entity, world.required_role_to_value
            )
        ):
            raise ValueError("consistency-only sequence set is inconsistent")
        if world.marginal_unbound_sequences != render_marginal_unbound_sequences(
            world.entity
        ):
            raise ValueError("marginal/unbound sequence set is inconsistent")


def check_completion(
    world: CompletionObligationWorld,
    generated: bytes,
) -> CompletionCheck:
    """Check generated bytes using only the supplied formal-world record."""

    if not isinstance(world, CompletionObligationWorld):
        raise TypeError("world must be a CompletionObligationWorld")
    if not isinstance(generated, bytes):
        raise TypeError("generated must be bytes")

    required = dict(world.required_role_to_value)
    known_roles = set(required)
    known_values = set(required.values())
    lines = generated.splitlines(keepends=True)
    termination_indices = tuple(
        index for index, line in enumerate(lines) if line == TERMINATOR
    )
    explicit_termination = bool(termination_indices)
    first_termination = termination_indices[0] if termination_indices else len(lines)
    claim_lines = lines[:first_termination]
    trailing_bytes = (
        b"".join(lines[first_termination + 1 :]) if explicit_termination else b""
    )

    claims: list[CompletionClaim] = []
    unparsed: list[bytes] = []
    for line_index, line in enumerate(claim_lines):
        matched = _CLAIM_PATTERN.fullmatch(line)
        if matched is None:
            unparsed.append(line)
            continue
        entity, role, value = (
            token.decode("ascii") for token in matched.groups()
        )
        claims.append(
            CompletionClaim(
                line_index=line_index,
                raw=line,
                entity=entity,
                role=role,
                value=value,
            )
        )

    unsupported: list[UnsupportedClaim] = []
    supported_claims: list[CompletionClaim] = []
    for claim in claims:
        reasons: list[str] = []
        if claim.entity != world.entity:
            reasons.append("unknown_entity")
        if claim.role not in known_roles:
            reasons.append("unknown_role")
        if claim.value not in known_values:
            reasons.append("unknown_value")
        if reasons:
            unsupported.append(UnsupportedClaim(claim, tuple(reasons)))
        else:
            supported_claims.append(claim)

    wrong = tuple(
        claim
        for claim in supported_claims
        if required[claim.role] != claim.value
    )
    completed = tuple(
        role
        for role in required
        if any(
            claim.role == role and claim.value == required[role]
            for claim in supported_claims
        )
    )
    missing = tuple(role for role in required if role not in completed)

    conflicts: list[ConflictingRepeat] = []
    for role in required:
        role_claims = [claim for claim in supported_claims if claim.role == role]
        distinct_values = tuple(dict.fromkeys(claim.value for claim in role_claims))
        if len(distinct_values) > 1:
            conflicts.append(
                ConflictingRepeat(
                    role=role,
                    values=distinct_values,
                    line_indices=tuple(claim.line_index for claim in role_claims),
                )
            )

    # Derive acceptance from the formal record and parsed bytes.  In
    # particular, do not consult ``accepted_full_completions``: that collection
    # is an independently compiled training/control surface whose corruption
    # must not change evaluation semantics.
    role_counts = Counter(claim.role for claim in supported_claims)
    exact_accepted = (
        len(claims) == len(required)
        and completed == tuple(required)
        and not missing
        and not wrong
        and not unsupported
        and not conflicts
        and not unparsed
        and len(termination_indices) == 1
        and not trailing_bytes
        and all(role_counts[role] == 1 for role in required)
    )
    return CompletionCheck(
        world_id=world.world_id,
        generated=generated,
        claims=tuple(claims),
        completed_obligations=completed,
        missing_obligations=missing,
        wrong_claims=wrong,
        unsupported_claims=tuple(unsupported),
        conflicting_repeats=tuple(conflicts),
        unparsed_content=tuple(unparsed),
        explicit_termination=explicit_termination,
        termination_count=len(termination_indices),
        terminated_early=explicit_termination and bool(missing),
        trailing_content=bool(trailing_bytes),
        trailing_bytes=trailing_bytes,
        exact_accepted=exact_accepted,
    )


def check_crossed_pair(
    pair: CompletionObligationPair,
    generated_a: bytes,
    generated_b: bytes,
) -> CrossedCompletionCheck:
    """Check each output on its matched world and on the paired other world."""

    if not isinstance(pair, CompletionObligationPair):
        raise TypeError("pair must be a CompletionObligationPair")
    a_on_a = check_completion(pair.world_a, generated_a)
    b_on_b = check_completion(pair.world_b, generated_b)
    a_on_b = check_completion(pair.world_b, generated_a)
    b_on_a = check_completion(pair.world_a, generated_b)
    matched_exact_count = int(a_on_a.exact_accepted) + int(b_on_b.exact_accepted)
    crossed_exact_count = int(a_on_b.exact_accepted) + int(b_on_a.exact_accepted)
    matched_pair_accepted = matched_exact_count == 2
    crossed_pair_accepted = crossed_exact_count == 2
    return CrossedCompletionCheck(
        pair_id=pair.pair_id,
        a_on_a=a_on_a,
        b_on_b=b_on_b,
        a_on_b=a_on_b,
        b_on_a=b_on_a,
        matched_exact_count=matched_exact_count,
        crossed_exact_count=crossed_exact_count,
        matched_pair_accepted=matched_pair_accepted,
        crossed_pair_accepted=crossed_pair_accepted,
        binding_sensitive_pair_accepted=(
            matched_pair_accepted and crossed_exact_count == 0
        ),
    )


evaluate_crossed_pair = check_crossed_pair
