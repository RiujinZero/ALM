def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _normalized_native_distribution(values: Sequence[float] | np.ndarray) -> np.ndarray:
    distribution = np.asarray(values, dtype=np.float64)
    if distribution.shape != (ALPHABET_SIZE,):
        raise ValueError("native distribution must have shape (256,)")
    if not np.all(np.isfinite(distribution)) or np.any(distribution < 0.0):
        raise ValueError("native distribution must be finite and non-negative")
    total = float(distribution.sum())
    if not math.isfinite(total) or total <= 0.0:
        raise ValueError("native distribution must have positive finite mass")
    result = np.array(distribution / total, dtype=np.float64, copy=True)
    result.flags.writeable = False
    return result


def _validated_effective_distribution(
    values: Sequence[float] | np.ndarray,
) -> np.ndarray:
    """Validate an already normalized route without perturbing exact bypasses."""

    distribution = np.asarray(values, dtype=np.float64)
    if distribution.shape != (ALPHABET_SIZE,):
        raise ValueError("effective distribution must have shape (256,)")
    if not np.all(np.isfinite(distribution)) or np.any(distribution < 0.0):
        raise ValueError("effective distribution must be finite and non-negative")
    if not np.isclose(float(distribution.sum()), 1.0, rtol=0.0, atol=1e-12):
        raise ValueError("effective distribution must sum to one")
    return np.array(distribution, dtype=np.float64, copy=True)


class NativeBodyTracker:
    """Track serialized-size estimates without mistaking episode state for anatomy."""

    def __init__(self, cortex: FrozenCortex) -> None:
        self.at_load = int(getattr(cortex, "embodied_bytes", -1))
        self.maximum_transient = self.at_load

    def observe(self, cortex: FrozenCortex) -> None:
        current = int(getattr(cortex, "embodied_bytes", -1))
        self.maximum_transient = max(self.maximum_transient, current)


def _prime(
    cortex: FrozenCortex,
    context: bytes,
    tracker: NativeBodyTracker | None = None,
) -> None:
    cortex.reset_episode()
    if context:
        cortex.observe_chunk_probabilities(
            np.frombuffer(context, dtype=np.uint8), learn=False
        )
    if tracker is not None:
        tracker.observe(cortex)


def _proper_prefixes(sequences: Sequence[bytes]) -> tuple[bytes, ...]:
    prefixes = {
        sequence[:index]
        for sequence in sequences
        for index in range(len(sequence))
    }
    return tuple(sorted(prefixes))


class NativePrefixTable:
    """Frozen p0(H, prefix) recorded by replaying each unique path once."""

    def __init__(
        self,
        cortex: FrozenCortex,
        prompt: bytes,
        tracker: NativeBodyTracker,
    ) -> None:
        self._cortex = cortex
        self.prompt = bytes(prompt)
        self._tracker = tracker
        self._values: dict[bytes, np.ndarray] = {}
        self.trajectory_replays = 0
        self.symbol_advances = 0

    def record(self, sequences: Sequence[bytes]) -> None:
        """Replay each unique completion and cache every first-seen prefix p0."""

        unique = tuple(sorted(set(sequences)))
        for sequence in unique:
            _prime(self._cortex, self.prompt, self._tracker)
            for index, symbol in enumerate(sequence):
                prefix = sequence[:index]
                current = _normalized_native_distribution(
                    self._cortex.predict_next_distribution()
                )
                if prefix in self._values:
                    if not np.array_equal(current, self._values[prefix]):
                        raise AssertionError(
                            "frozen native p0 is not replay-deterministic"
                        )
                else:
                    self._values[prefix] = current
                self._cortex.advance_observation(symbol, learn=False)
                self.symbol_advances += 1
                self._tracker.observe(self._cortex)
            self.trajectory_replays += 1

    def subset(self, sequences: Sequence[bytes]) -> dict[bytes, np.ndarray]:
        prefixes = _proper_prefixes(sequences)
        missing = [prefix for prefix in prefixes if prefix not in self._values]
        if missing:
            raise AssertionError("native prefix table is incomplete")
        return {prefix: self._values[prefix] for prefix in prefixes}

    def distribution(self, prefix: bytes) -> np.ndarray:
        if prefix not in self._values:
            raise KeyError(prefix)
        return np.array(self._values[prefix], copy=True)

    @property
    def prefixes(self) -> tuple[bytes, ...]:
        return tuple(sorted(self._values))

    def fingerprint(self) -> str:
        digest = hashlib.sha256()
        digest.update(b"NativePrefixTable-v1")
        digest.update(len(self.prompt).to_bytes(8, "little"))
        digest.update(self.prompt)
        for prefix in self.prefixes:
            digest.update(len(prefix).to_bytes(4, "little"))
            digest.update(prefix)
            digest.update(self._values[prefix].astype("<f8", copy=False).tobytes())
        return digest.hexdigest()


def _binding_swapped_sequences(
    world: obligation.CompletionObligationWorld,
) -> tuple[bytes, ...]:
    mapping = world.required_mapping
    first, second = obligation.ROLES[:2]
    mapping[first], mapping[second] = mapping[second], mapping[first]
    return obligation.render_full_completions(world.entity, mapping)


def _accepted_sets(
    world: obligation.CompletionObligationWorld,
    counterpart: obligation.CompletionObligationWorld,
) -> dict[str, tuple[bytes, ...]]:
    sets = {
        "correct": tuple(world.accepted_full_completions),
        # Keep actual-prompt p0 fixed and replace only the externally supplied
        # accepted binding.  This is a wrong-target control, not a swap of the
        # cortex's retained history/state.
        "paired_wrong_target": tuple(counterpart.accepted_full_completions),
        "binding_swapped": _binding_swapped_sequences(world),
        "consistency_only": tuple(world.consistency_accepted_sequences),
        "marginal_unbound": tuple(world.marginal_unbound_sequences),
    }
    if tuple(sets) != POTENTIAL_SET_NAMES:
        raise AssertionError("potential-set coverage changed")
    if sets["correct"] == sets["paired_wrong_target"]:
        raise AssertionError("paired wrong target aliases the correct completion set")
    if sets["binding_swapped"] in (
        sets["correct"],
        sets["paired_wrong_target"],
    ):
        raise AssertionError("binding-swap set aliases another exact control")
    for name, sequences in sets.items():
        if not sequences or len(sequences) != len(set(sequences)):
            raise ValueError(f"{name} completion set must be nonempty and unique")
        if any(not sequence.endswith(obligation.TERMINATOR) for sequence in sequences):
            raise ValueError(f"{name} completion lacks the explicit terminator")
    return sets


def _potential_record(potential: ExactCompletionPotential) -> dict[str, Any]:
    diagnostics = asdict(potential.diagnostics)
    diagnostics.update(
        {
            "fingerprint": potential.fingerprint(),
            "accepted_sequence_sha256": _sequence_set_sha256(
                potential.accepted_sequences
            ),
            "root_has_nonzero_literal_path_support": math.isfinite(
                potential.accepted_log_mass
            ),
        }
    )
    return diagnostics


def _sequence_set_sha256(sequences: Sequence[bytes]) -> str:
    digest = hashlib.sha256()
    for sequence in sorted(sequences):
        digest.update(len(sequence).to_bytes(4, "little"))
        digest.update(sequence)
    return digest.hexdigest()


def _different_decision_witness(
    correct: ExactCompletionPotential,
    wrong: ExactCompletionPotential,
) -> dict[str, Any]:
    """Find the first identical prefix where only the accepted set changes q."""

    shared = sorted(
        set(correct.internal_prefixes) & set(wrong.internal_prefixes),
        key=lambda prefix: (len(prefix), prefix),
    )
    for prefix in shared:
        correct_base = correct.base_distribution(prefix)
        wrong_base = wrong.base_distribution(prefix)
        if not np.array_equal(correct_base, wrong_base):
            raise AssertionError("potential variants do not share the same frozen p0")
        left = correct.distribution(prefix)
        right = wrong.distribution(prefix)
        l1 = float(np.abs(left - right).sum())
        if l1 > 0.0:
            return {
                "found": True,
                "emitted_prefix_bytes": len(prefix),
                "emitted_prefix_sha256": _sha256(prefix),
                "emitted_prefix_text": prefix.decode(
                    "utf-8", errors="backslashreplace"
                ),
                "base_distribution_sha256": _sha256(
                    correct_base.astype("<f8", copy=False).tobytes()
                ),
                "base_distribution_exactly_equal": True,
                "correct_distribution_sha256": _sha256(
                    left.astype("<f8", copy=False).tobytes()
                ),
                "wrong_distribution_sha256": _sha256(
                    right.astype("<f8", copy=False).tobytes()
                ),
                "route_l1": l1,
                "correct_argmax": int(np.argmax(left)),
                "wrong_argmax": int(np.argmax(right)),
                "only_changed_input": "long_horizon_accepted_completion_set",
            }
    raise AssertionError(
        "correct and paired-wrong accepted sets never change a shared-prefix decision"
    )


def compile_world(
    cortex: FrozenCortex,
    world: obligation.CompletionObligationWorld,
    counterpart: obligation.CompletionObligationWorld,
    tracker: NativeBodyTracker,
) -> CompiledWorld:
    """Compile all receiver controls under this world's actual native prompt."""

    sets = _accepted_sets(world, counterpart)
    union = tuple(sorted({sequence for values in sets.values() for sequence in values}))
    table = NativePrefixTable(cortex, world.prompt, tracker)
    table.record(union)
    potentials = {
        name: ExactCompletionPotential.from_prefix_distributions(
            sequences,
            table.subset(sequences),
            alphabet_size=ALPHABET_SIZE,
        )
        for name, sequences in sets.items()
    }
    for name, potential in potentials.items():
        if not math.isfinite(potential.accepted_log_mass):
            raise RuntimeError(
                f"native p0 has zero accepted completion support for {name}"
            )
    zero = potentials["correct"].distribution(b"", gain=0.0)
    if not np.allclose(
        zero, table.distribution(b""), rtol=0.0, atol=1e-15
    ):
        raise AssertionError("gain-zero root is not an exact native bypass")
    witness = _different_decision_witness(
        potentials["correct"], potentials["paired_wrong_target"]
    )
    return CompiledWorld(world, counterpart, sets, potentials, table, witness)


def _arm_specs() -> dict[str, ArmSpec]:
    specs = {
        "native": ArmSpec(None, False, 0.0),
        "correct_exact_h": ArmSpec("correct", True, 1.0),
        "computed_but_disconnected": ArmSpec("correct", False, 1.0),
        "zero_strength": ArmSpec("correct", True, 0.0),
        "paired_wrong_target_h": ArmSpec("paired_wrong_target", True, 1.0),
        "binding_swapped_h": ArmSpec("binding_swapped", True, 1.0),
        "consistency_only_h": ArmSpec("consistency_only", True, 1.0),
        "marginal_unbound_h": ArmSpec("marginal_unbound", True, 1.0),
        "false_positive_floor_1em3": ArmSpec(
            "correct", True, 1.0, FALSE_POSITIVE_FLOOR
        ),
    }
    if tuple(specs) != ARM_NAMES:
        raise AssertionError("arm coverage changed")
    return specs


def _sample_with_uniform(distribution: np.ndarray, uniform: float) -> int:
    return min(
        int(np.searchsorted(np.cumsum(distribution), uniform, side="right")),
        ALPHABET_SIZE - 1,
    )


def generate(
    cortex: FrozenCortex,
    compiled: CompiledWorld,
    spec: ArmSpec,
    *,
    horizon: int,
    uniform_draws: np.ndarray | None,
    tracker: NativeBodyTracker,
) -> GeneratedTrace:
    """Generate one byte at a time with no semantic stopping side channel."""

    if horizon < 1:
        raise ValueError("generation horizon must be positive")
    if uniform_draws is not None:
        draws = np.asarray(uniform_draws, dtype=np.float64)
        if draws.shape != (horizon,) or np.any((draws < 0.0) | (draws >= 1.0)):
            raise ValueError("uniform draws must have shape (horizon,) in [0,1)")
    else:
        draws = None
    potential = (
        None
        if spec.potential_name is None
        else compiled.potentials[spec.potential_name]
    )
    _prime(cortex, compiled.world.prompt, tracker)
    generated = bytearray()
    effective_digest = hashlib.sha256()
    base_digest = hashlib.sha256()
    route_l1_values: list[float] = []
    first_intervention: int | None = None
    off_trie_steps = 0
    selected_zero_support = 0
    fallback_count = 0
    for step in range(horizon):
        prefix = bytes(generated)
        base = _normalized_native_distribution(cortex.predict_next_distribution())
        base_digest.update(base.astype("<f8", copy=False).tobytes())
        if potential is None or not spec.connected or spec.gain == 0.0:
            effective = np.array(base, copy=True)
        else:
            status = potential.status(prefix)
            if status is PrefixStatus.LEAF:
                raise AssertionError("generation requested a distribution after a leaf")
            if status is PrefixStatus.OFF_TRIE:
                off_trie_steps += 1
                if spec.false_positive_floor == 0.0:
                    raise AssertionError("exact h left its accepted trie; no fallback")
                effective = potential.distribution(
                    prefix,
                    gain=spec.gain,
                    false_positive_floor=spec.false_positive_floor,
                    off_trie_base_distribution=base,
                )
            else:
                compiled_base = potential.base_distribution(prefix)
                if not np.allclose(base, compiled_base, rtol=0.0, atol=1e-15):
                    raise AssertionError(
                        "live native p0 changed from the prompt-conditioned compile"
                    )
                effective = potential.distribution(
                    prefix,
                    gain=spec.gain,
                    false_positive_floor=spec.false_positive_floor,
                )
        effective = _validated_effective_distribution(effective)
        l1 = float(np.abs(effective - base).sum())
        route_l1_values.append(l1)
        if l1 > 0.0 and first_intervention is None:
            first_intervention = step
        effective_digest.update(effective.astype("<f8", copy=False).tobytes())
        symbol = (
            int(np.argmax(effective))
            if draws is None
            else _sample_with_uniform(effective, float(draws[step]))
        )
        if base[symbol] <= 0.0:
            selected_zero_support += 1
            raise AssertionError("route selected a byte absent from native support")
        generated.append(symbol)
        cortex.advance_observation(symbol, learn=False)
        tracker.observe(cortex)
        if generated.endswith(obligation.TERMINATOR):
            break
    data = bytes(generated)
    exact_leaf = (
        None
        if potential is None or not spec.connected or spec.gain == 0.0
        else data in potential.accepted_sequences
    )
    if (
        potential is not None
        and spec.connected
        and spec.gain > 0.0
        and spec.false_positive_floor == 0.0
        and not exact_leaf
    ):
        raise AssertionError("exact potential did not terminate on an accepted leaf")
    return GeneratedTrace(
        data=data,
        probability_sha256=effective_digest.hexdigest(),
        base_probability_sha256=base_digest.hexdigest(),
        steps=len(data),
        route_changed_steps=sum(value > 0.0 for value in route_l1_values),
        first_route_intervention=first_intervention,
        mean_route_l1=float(np.mean(route_l1_values)),
        maximum_route_l1=max(route_l1_values),
        off_trie_steps=off_trie_steps,
        selected_zero_base_support=selected_zero_support,
        fallback_count=fallback_count,
        terminated=data.endswith(obligation.TERMINATOR),
        exact_leaf_reached=exact_leaf,
    )


def _first_divergence(left: bytes, right: bytes) -> int | None:
    for index, (a, b) in enumerate(zip(left, right, strict=False)):
        if a != b:
            return index
    return None if len(left) == len(right) else min(len(left), len(right))


def _generation_diagnostics(payload: bytes) -> dict[str, Any]:
    length = max(len(payload), 1)
    printable = sum(
        byte in (9, 10, 13) or 32 <= byte <= 126 for byte in payload
    ) / length
    maximum_run = 0
    run = 0
    previous: int | None = None
    for byte in payload:
        run = run + 1 if byte == previous else 1
        maximum_run = max(maximum_run, run)
        previous = byte
    try:
        payload.decode("utf-8")
        valid_utf8 = True
    except UnicodeDecodeError:
        valid_utf8 = False
    fourgrams = [
        payload[index : index + 4]
        for index in range(max(len(payload) - 3, 0))
    ]
    return {
        "bytes": len(payload),
        "sha256": _sha256(payload),
        "printable_fraction": printable,
        "valid_utf8": valid_utf8,
        "unique_byte_fraction": len(set(payload)) / length,
        "maximum_identical_byte_run": maximum_run,
        "fourgram_repeat_fraction": (
            0.0 if not fourgrams else 1.0 - len(set(fourgrams)) / len(fourgrams)
        ),
        "explicit_terminator": payload.endswith(obligation.TERMINATOR),
    }


