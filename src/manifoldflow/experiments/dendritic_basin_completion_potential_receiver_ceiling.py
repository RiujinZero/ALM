"""Dev-only exact completion-potential receiver ceiling on a frozen cortex.

This assay asks a deliberately narrow question: if a full-completion event and
literal answer repertoire are specified exactly, can its prefix potential use
nonzero literal-path support in a frozen native byte model?  The score is

    h(H, s) = P_native(accepted full completion | actual prompt H, prefix s),

not a next-byte training label.  Bytes are only the actuator through which the
long-horizon accepted-subtree mass changes generation.  The independent
checker sees only the formal world and completed generated bytes.

Only deterministic synthetic development worlds are constructed here.  There
is no corpus, configurable split, parameter learning, protected payload, or
natural-chat quality claim.  Oracle prefixes are replayed offline to compile
the frozen base distribution; scored generation itself is free running.
"""

