"""Probe a frozen-native dual-state antecedent production route.

This is an evaluation-only expression ceiling, not a deployable goal policy.
For each schema-v4 crossover side, one frozen cortex (``base``) is primed with
the complete interrupted context while a second frozen cortex (``route``) is
primed with one explicitly audited causal antecedent:

* ``correct_antecedent`` uses that side's ``audit_subranges.original_prefix``;
* ``swapped_antecedent`` uses the paired side's original prefix;
* ``duplicate_current_state_sham`` primes both states with the full context;
* ``disconnected_correct_antecedent`` computes the correct route but sets
  beta to exactly zero; and
* ``static_query_no_feedback`` keeps the correct route state fixed while the
  base follows teacher-forced or generated bytes.

The original prefix ends at the target USER turn and precedes the common
interruption bridge.  It contains no withheld ASSISTANT response and no future
goal-target range.  Choosing the matching prefix from pair metadata is the
oracle operation.  The contents themselves remain ordinary causal prompt
bytes; no answer vector, response byte, duration, or output schedule is given
to the route.

At each byte, the two normalized 256-way predictions are combined by a fixed
geometric/product-of-experts interpolation, ``base**(1-beta) * route**beta``.
The teacher-forced target byte or greedily emitted byte is then advanced into
both states with ``learn=False``.  Therefore the route must remain useful under
its own emitted trajectory during free generation rather than merely score a
finished response.

The CLI defaults to development data and refuses to open the test split unless
``--allow-test`` is explicit.  Gain selection and confirmatory test execution
belong in separate, preregistered invocations.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from dataclasses import dataclass
from math import log2
from pathlib import Path
from typing import Any, Protocol

import numpy as np

from manifoldflow.experiments.dendritic_basin_shared_goal_crossover_ablation import (
    _read_jsonl,
    _slice,
)
from manifoldflow.experiments.dendritic_basin_shared_goal_generation_ablation import (
    _paired_reference_discrimination,
)

SCHEMA_VERSION = 4
CONDITION_NAMES = (
    "native_base",
    "correct_antecedent",
    "swapped_antecedent",
    "disconnected_correct_antecedent",
    "duplicate_current_state_sham",
    "static_query_no_feedback",
)
BOOTSTRAP_CONTRASTS = (
    ("correct_vs_native", "native_base"),
    ("correct_vs_swapped", "swapped_antecedent"),
    ("recurrent_correct_vs_static", "static_query_no_feedback"),
)


class FrozenCortex(Protocol):
    """Small native/fake-cortex surface needed by the experiment."""

    def reset_episode(self) -> None: ...

    def observe_chunk_probabilities(
        self, byte_ids: np.ndarray, *, learn: bool
    ) -> Any: ...

    def predict_next_distribution(self) -> np.ndarray: ...

    def advance_observation(self, byte_id: int, *, learn: bool) -> Any: ...


@dataclass(frozen=True)
class AntecedentCrossoverPair:
    """Only the causal and scoring fields used by this experiment."""

    pair_id: str
    context_a: bytes
    context_b: bytes
    original_prefix_a: bytes
    original_prefix_b: bytes
    response_a: bytes
    response_b: bytes
    common_suffix_bytes: int


@dataclass(frozen=True)
class RolloutTrace:
    """A frozen rollout with distributions retained for exact invariants."""

    observed: bytes
    combined_distributions: np.ndarray
    base_distributions: np.ndarray
    route_distributions: np.ndarray | None
    target_bits: float | None
    mode: str

    @property
    def steps(self) -> int:
        return len(self.observed)

    @property
    def target_bpb(self) -> float | None:
        if self.target_bits is None:
            return None
        return self.target_bits / max(self.steps, 1)


@dataclass(frozen=True)
class SideConditionResult:
    teacher_forced: RolloutTrace
    greedy: RolloutTrace


def _range_interval(record: dict[str, Any]) -> tuple[int, int]:
    start = int(record["start"])
    end = int(record["end"])
    if start < 0 or end <= start:
        raise ValueError("sidecar range must be nonempty and ordered")
    return start, end


def _ranges_overlap(left: dict[str, Any], right: dict[str, Any]) -> bool:
    left_start, left_end = _range_interval(left)
    right_start, right_end = _range_interval(right)
    return left_start < right_end and right_start < left_end


def load_antecedent_pairs(
    dataset_dir: Path, split: str
) -> list[AntecedentCrossoverPair]:
    """Load schema-v4 pairs without reading any future-target payload.

    Responses are loaded solely as teacher-forced/evaluation targets.  The
    ``goal_target_a/b`` ranges are intentionally never sliced here.
    """

    manifest = json.loads((dataset_dir / "manifest.json").read_text(encoding="utf-8"))
    if int(manifest.get("schema_version", -1)) != SCHEMA_VERSION:
        raise ValueError("antecedent production requires corpus schema version 4")
    rows = _read_jsonl(dataset_dir / f"{split}_pairs.jsonl")
    blob = (dataset_dir / f"{split}_pairs.bin").read_bytes()
    pairs: list[AntecedentCrossoverPair] = []
    for row_index, row in enumerate(rows):
        if int(row.get("schema_version", -1)) != SCHEMA_VERSION:
            raise ValueError(f"{split} pair {row_index} is not schema version 4")
        invariants = row.get("invariants")
        if not isinstance(invariants, dict) or not all(
            bool(value) for value in invariants.values()
        ):
            raise ValueError(f"{split} pair {row_index} has a false invariant")
        ranges = row["blob_ranges"]
        audits = row.get("audit_subranges", {})
        required_audits = {"original_prefix_a", "original_prefix_b"}
        if not required_audits.issubset(audits):
            raise ValueError(f"{split} pair {row_index} lacks original-prefix audits")

        context_a = _slice(blob, ranges["context_a"])
        context_b = _slice(blob, ranges["context_b"])
        response_a = _slice(blob, ranges["response_a"])
        response_b = _slice(blob, ranges["response_b"])
        original_a = _slice(blob, audits["original_prefix_a"])
        original_b = _slice(blob, audits["original_prefix_b"])
        common = int(row["common_suffix"]["bytes"])
        if common <= 0 or common > min(len(context_a), len(context_b)):
            raise ValueError(f"{split} pair {row_index} has invalid common suffix")
        if context_a[-common:] != context_b[-common:]:
            raise ValueError(f"{split} pair {row_index} common suffix differs")
        if original_a != context_a[:-common] or original_b != context_b[:-common]:
            raise ValueError(
                f"{split} pair {row_index} original prefix does not end at bridge"
            )
        context_a_start, _ = _range_interval(ranges["context_a"])
        context_b_start, _ = _range_interval(ranges["context_b"])
        original_a_start, original_a_end = _range_interval(audits["original_prefix_a"])
        original_b_start, original_b_end = _range_interval(audits["original_prefix_b"])
        if original_a_start != context_a_start or original_b_start != context_b_start:
            raise ValueError(f"{split} pair {row_index} prefix range starts late")
        if original_a_end != int(row["common_suffix"]["context_a_start"]):
            raise ValueError(
                f"{split} pair {row_index} A prefix/bridge boundary differs"
            )
        if original_b_end != int(row["common_suffix"]["context_b_start"]):
            raise ValueError(
                f"{split} pair {row_index} B prefix/bridge boundary differs"
            )
        episodes = row.get("episodes", {})
        for side, original in (("a", original_a), ("b", original_b)):
            metadata = episodes.get(side)
            if not isinstance(metadata, dict):
                raise ValueError(f"{split} pair {row_index} lacks episode {side}")
            if int(metadata["unanswered_prefix_bytes"]) != len(original):
                raise ValueError(
                    f"{split} pair {row_index} {side} prefix length differs"
                )
            if int(metadata["target_user_content_end"]) != len(original):
                raise ValueError(
                    f"{split} pair {row_index} {side} prefix extends past USER"
                )
        for prefix_name in ("original_prefix_a", "original_prefix_b"):
            for forbidden_name in (
                "response_a",
                "response_b",
                "full_response_a",
                "full_response_b",
                "goal_target_a",
                "goal_target_b",
            ):
                if forbidden_name in ranges and _ranges_overlap(
                    audits[prefix_name], ranges[forbidden_name]
                ):
                    raise ValueError(
                        f"{split} pair {row_index} {prefix_name} overlaps "
                        f"{forbidden_name}"
                    )
        pairs.append(
            AntecedentCrossoverPair(
                pair_id=str(row["pair_id"]),
                context_a=context_a,
                context_b=context_b,
                original_prefix_a=original_a,
                original_prefix_b=original_b,
                response_a=response_a,
                response_b=response_b,
                common_suffix_bytes=common,
            )
        )
    if not pairs:
        raise ValueError(f"{split} split contains no crossover pairs")
    return pairs


def normalized_distribution(values: Any) -> np.ndarray:
    """Validate and normalize one native 256-way distribution."""

    distribution = np.asarray(values, dtype=np.float64).reshape(-1)
    if distribution.shape != (256,):
        raise ValueError("native cortex distribution must have shape (256,)")
    if not np.all(np.isfinite(distribution)) or np.any(distribution < 0.0):
        raise ValueError("native cortex distribution must be finite and nonnegative")
    total = float(np.sum(distribution))
    if total <= 0.0:
        raise ValueError("native cortex distribution has no probability mass")
    return distribution / total


def geometric_product_distribution(
    base: Any,
    route: Any,
    beta: float,
    *,
    minimum_probability: float = 1e-300,
) -> np.ndarray:
    """Combine normalized experts; beta=0 returns the base bit-for-bit.

    Both inputs are evaluated and validated even at beta zero, keeping the
    disconnected route compute-shaped like the active dual-state conditions.
    """

    if not 0.0 <= beta <= 1.0:
        raise ValueError("beta must be in [0, 1]")
    if not 0.0 < minimum_probability < 1.0:
        raise ValueError("minimum_probability must lie strictly between zero and one")
    base_input = np.asarray(base, dtype=np.float64).reshape(-1)
    route_input = np.asarray(route, dtype=np.float64).reshape(-1)
    base_distribution = normalized_distribution(base_input)
    route_distribution = normalized_distribution(route_input)
    if beta == 0.0:
        # Callers supply the output of ``_predict``, which is already a
        # checked normalized distribution.  Preserve those exact bits instead
        # of dividing by a sum a second time; that extra normalization made the
        # disconnected control differ from native by floating-point roundoff.
        if np.isclose(float(base_input.sum()), 1.0, rtol=0.0, atol=1e-12):
            return base_input.copy()
        return base_distribution.copy()
    if np.array_equal(base_input, route_input):
        # This is the exact mathematical duplicate-state identity.  Returning
        # the supplied normalized base avoids introducing log/exp roundoff.
        if np.isclose(float(base_input.sum()), 1.0, rtol=0.0, atol=1e-12):
            return base_input.copy()
        return base_distribution.copy()
    log_weight = (1.0 - beta) * np.log(
        np.maximum(base_distribution, minimum_probability)
    ) + beta * np.log(np.maximum(route_distribution, minimum_probability))
    log_weight -= float(np.max(log_weight))
    combined = np.exp(log_weight)
    combined /= float(np.sum(combined))
    return combined


def _prime(cortex: FrozenCortex, payload: bytes) -> None:
    cortex.reset_episode()
    if payload:
        cortex.observe_chunk_probabilities(
            np.frombuffer(payload, dtype=np.uint8), learn=False
        )


def _predict(cortex: FrozenCortex) -> np.ndarray:
    return normalized_distribution(cortex.predict_next_distribution())


def _advance(cortex: FrozenCortex, byte_id: int) -> None:
    cortex.advance_observation(int(byte_id), learn=False)


def native_teacher_forced_trace(
    cortex: FrozenCortex, context: bytes, target: bytes
) -> RolloutTrace:
    """Score a target under one reset, frozen native state."""

    if not target:
        raise ValueError("teacher-forced target must be nonempty")
    _prime(cortex, context)
    rows = np.empty((len(target), 256), dtype=np.float64)
    bits = 0.0
    for position, byte_id in enumerate(target):
        distribution = _predict(cortex)
        rows[position] = distribution
        bits -= log2(max(float(distribution[byte_id]), 1e-300))
        _advance(cortex, byte_id)
    return RolloutTrace(target, rows, rows.copy(), None, bits, "teacher_forced")


def native_greedy_trace(
    cortex: FrozenCortex, context: bytes, *, max_new_bytes: int
) -> RolloutTrace:
    """Generate a fixed-horizon greedy native continuation."""

    if max_new_bytes < 1:
        raise ValueError("max_new_bytes must be positive")
    _prime(cortex, context)
    rows = np.empty((max_new_bytes, 256), dtype=np.float64)
    emitted = bytearray()
    for position in range(max_new_bytes):
        distribution = _predict(cortex)
        rows[position] = distribution
        byte_id = int(np.argmax(distribution))
        emitted.append(byte_id)
        _advance(cortex, byte_id)
    return RolloutTrace(bytes(emitted), rows, rows.copy(), None, None, "greedy")


def dual_teacher_forced_trace(
    base_cortex: FrozenCortex,
    route_cortex: FrozenCortex,
    *,
    base_context: bytes,
    route_prefix: bytes,
    target: bytes,
    beta: float,
    advance_route: bool = True,
    minimum_probability: float = 1e-300,
) -> RolloutTrace:
    """Teacher-force one target through coupled base and antecedent states."""

    if not target:
        raise ValueError("teacher-forced target must be nonempty")
    _prime(base_cortex, base_context)
    _prime(route_cortex, route_prefix)
    base_rows = np.empty((len(target), 256), dtype=np.float64)
    route_rows = np.empty_like(base_rows)
    combined_rows = np.empty_like(base_rows)
    bits = 0.0
    for position, byte_id in enumerate(target):
        base = _predict(base_cortex)
        route = _predict(route_cortex)
        combined = geometric_product_distribution(
            base, route, beta, minimum_probability=minimum_probability
        )
        base_rows[position] = base
        route_rows[position] = route
        combined_rows[position] = combined
        bits -= log2(max(float(combined[byte_id]), 1e-300))
        _advance(base_cortex, byte_id)
        if advance_route:
            _advance(route_cortex, byte_id)
    return RolloutTrace(
        target,
        combined_rows,
        base_rows,
        route_rows,
        bits,
        "teacher_forced",
    )


def dual_greedy_trace(
    base_cortex: FrozenCortex,
    route_cortex: FrozenCortex,
    *,
    base_context: bytes,
    route_prefix: bytes,
    beta: float,
    max_new_bytes: int,
    advance_route: bool = True,
    minimum_probability: float = 1e-300,
) -> RolloutTrace:
    """Free-run both recurrent states on their shared greedy emissions."""

    if max_new_bytes < 1:
        raise ValueError("max_new_bytes must be positive")
    _prime(base_cortex, base_context)
    _prime(route_cortex, route_prefix)
    base_rows = np.empty((max_new_bytes, 256), dtype=np.float64)
    route_rows = np.empty_like(base_rows)
    combined_rows = np.empty_like(base_rows)
    emitted = bytearray()
    for position in range(max_new_bytes):
        base = _predict(base_cortex)
        route = _predict(route_cortex)
        combined = geometric_product_distribution(
            base, route, beta, minimum_probability=minimum_probability
        )
        base_rows[position] = base
        route_rows[position] = route
        combined_rows[position] = combined
        byte_id = int(np.argmax(combined))
        emitted.append(byte_id)
        # The same internally emitted byte advances both causal states.  No
        # teacher/evaluator byte is available on this path.
        _advance(base_cortex, byte_id)
        if advance_route:
            _advance(route_cortex, byte_id)
    return RolloutTrace(
        bytes(emitted),
        combined_rows,
        base_rows,
        route_rows,
        None,
        "greedy",
    )


def _condition_route_prefix(
    pair: AntecedentCrossoverPair, side: str, condition: str
) -> bytes | None:
    if side not in {"a", "b"}:
        raise ValueError("side must be 'a' or 'b'")
    if condition == "native_base":
        return None
    context = pair.context_a if side == "a" else pair.context_b
    own = pair.original_prefix_a if side == "a" else pair.original_prefix_b
    other = pair.original_prefix_b if side == "a" else pair.original_prefix_a
    if condition in {
        "correct_antecedent",
        "disconnected_correct_antecedent",
        "static_query_no_feedback",
    }:
        return own
    if condition == "swapped_antecedent":
        return other
    if condition == "duplicate_current_state_sham":
        return context
    raise ValueError(f"unknown condition: {condition}")


def evaluate_side_condition(
    base_cortex: FrozenCortex,
    route_cortex: FrozenCortex,
    pair: AntecedentCrossoverPair,
    *,
    side: str,
    condition: str,
    beta: float,
    max_new_bytes: int,
    minimum_probability: float = 1e-300,
) -> SideConditionResult:
    """Run teacher-forced and free endpoints for one pair side/condition."""

    if condition not in CONDITION_NAMES:
        raise ValueError(f"unknown condition: {condition}")
    context = pair.context_a if side == "a" else pair.context_b
    target = pair.response_a if side == "a" else pair.response_b
    if not target:
        raise ValueError("teacher-forced response must be nonempty")
    # Free generation has a fixed evaluator-configured horizon.  In
    # particular, a short withheld reference must not reveal its duration to
    # the generator by shortening the rollout.
    horizon = max_new_bytes
    route_prefix = _condition_route_prefix(pair, side, condition)
    if condition == "native_base":
        return SideConditionResult(
            native_teacher_forced_trace(base_cortex, context, target),
            native_greedy_trace(base_cortex, context, max_new_bytes=horizon),
        )
    active_beta = 0.0 if condition == "disconnected_correct_antecedent" else beta
    advance_route = condition != "static_query_no_feedback"
    assert route_prefix is not None
    return SideConditionResult(
        dual_teacher_forced_trace(
            base_cortex,
            route_cortex,
            base_context=context,
            route_prefix=route_prefix,
            target=target,
            beta=active_beta,
            advance_route=advance_route,
            minimum_probability=minimum_probability,
        ),
        dual_greedy_trace(
            base_cortex,
            route_cortex,
            base_context=context,
            route_prefix=route_prefix,
            beta=active_beta,
            max_new_bytes=horizon,
            advance_route=advance_route,
            minimum_probability=minimum_probability,
        ),
    )


def common_prefix_bytes(left: bytes, right: bytes) -> int:
    count = 0
    for a, b in zip(left, right, strict=False):
        if a != b:
            break
        count += 1
    return count


def _trace_sha256(trace: RolloutTrace) -> str:
    digest = hashlib.sha256()
    digest.update(trace.observed)
    digest.update(trace.combined_distributions.tobytes(order="C"))
    return digest.hexdigest()


def _trace_report(trace: RolloutTrace, reference: bytes) -> dict[str, Any]:
    horizon_reference = reference[: len(trace.observed)]
    exact_prefix = {
        str(width): (
            None
            if len(trace.observed) < width or len(reference) < width
            else trace.observed[:width] == reference[:width]
        )
        for width in (8, 16, 32)
    }
    return {
        "mode": trace.mode,
        "steps": trace.steps,
        "target_bits": trace.target_bits,
        "target_bpb": trace.target_bpb,
        "trace_sha256": _trace_sha256(trace),
        "emitted_hex": trace.observed.hex(),
        "emitted_text": trace.observed.decode("utf-8", errors="replace"),
        "exact_reference_horizon": (
            None
            if len(reference) < len(trace.observed)
            else trace.observed == horizon_reference
        ),
        "exact_reference_prefix": exact_prefix,
        "common_prefix_bytes": common_prefix_bytes(trace.observed, horizon_reference),
        "common_prefix_fraction": common_prefix_bytes(trace.observed, horizon_reference)
        / max(len(horizon_reference), 1),
    }


def _side_report(result: SideConditionResult, reference: bytes) -> dict[str, Any]:
    return {
        "teacher_forced": _trace_report(result.teacher_forced, reference),
        "greedy": _trace_report(result.greedy, reference),
    }


def _condition_pair_endpoints(
    by_side: dict[str, SideConditionResult],
    pair: AntecedentCrossoverPair,
    *,
    lexical_dimensions: int,
) -> dict[str, Any]:
    teacher_bpb = [by_side[side].teacher_forced.target_bpb for side in ("a", "b")]
    if any(value is None for value in teacher_bpb):
        raise AssertionError("teacher-forced trace lacks target BPB")
    generated_a = by_side["a"].greedy.observed
    generated_b = by_side["b"].greedy.observed
    prefix_exact: dict[str, list[bool | None]] = {}
    for width in (8, 16, 32):
        prefix_exact[str(width)] = [
            None
            if len(generated) < width or len(reference) < width
            else generated[:width] == reference[:width]
            for generated, reference in (
                (generated_a, pair.response_a),
                (generated_b, pair.response_b),
            )
        ]
    horizon_exact = [
        (
            None
            if len(reference) < len(generated)
            else generated == reference[: len(generated)]
        )
        for generated, reference in (
            (generated_a, pair.response_a),
            (generated_b, pair.response_b),
        )
    ]
    return {
        "mean_teacher_forced_bpb": float(
            np.mean(np.asarray(teacher_bpb, dtype=np.float64))
        ),
        "exact_prefix": {**prefix_exact, "horizon": horizon_exact},
        "paired_raw_byte_ngram": _paired_reference_discrimination(
            generated_a,
            generated_b,
            pair.response_a,
            pair.response_b,
            dimensions=lexical_dimensions,
        ),
    }


def aggregate_pair_reports(
    reports: list[dict[str, Any]],
) -> dict[str, dict[str, Any]]:
    """Aggregate condition endpoints without pooling pair sides as pairs."""

    if not reports:
        raise ValueError("cannot aggregate an empty pair report list")
    result: dict[str, dict[str, Any]] = {}
    native_bpb = np.asarray(
        [
            row["condition_endpoints"]["native_base"]["mean_teacher_forced_bpb"]
            for row in reports
        ],
        dtype=np.float64,
    )
    for condition in CONDITION_NAMES:
        endpoints = [row["condition_endpoints"][condition] for row in reports]
        bpb = np.asarray(
            [row["mean_teacher_forced_bpb"] for row in endpoints],
            dtype=np.float64,
        )
        prefix_rates: dict[str, dict[str, float | int | None]] = {}
        for label in ("8", "16", "32", "horizon"):
            values = [
                value
                for row in endpoints
                for value in row["exact_prefix"][label]
                if value is not None
            ]
            prefix_rates[label] = {
                "eligible_sides": len(values),
                "exact_fraction": (
                    None if not values else float(np.mean(np.asarray(values)))
                ),
            }
        margins = np.asarray(
            [
                row["paired_raw_byte_ngram"]["correct_minus_crossed_margin"]
                for row in endpoints
            ],
            dtype=np.float64,
        )
        result[condition] = {
            "pairs": len(reports),
            "mean_teacher_forced_bpb": float(np.mean(bpb)),
            "mean_teacher_forced_bpb_improvement_vs_native": float(
                np.mean(native_bpb - bpb)
            ),
            "exact_reference_prefix_rates": prefix_rates,
            "paired_raw_byte_ngram_correct_minus_crossed": {
                "mean_margin": float(np.mean(margins)),
                "positive_pair_fraction": float(np.mean(margins > 0.0)),
            },
        }
    return result


def _paired_bootstrap_summary(
    values: np.ndarray, *, resample_indices: np.ndarray
) -> dict[str, float | int | bool]:
    """Summarize one pair-level contrast with shared bootstrap draws."""

    values = np.asarray(values, dtype=np.float64)
    indices = np.asarray(resample_indices)
    if values.ndim != 1 or not len(values):
        raise ValueError("cannot summarize an empty or non-vector pair contrast")
    if not np.all(np.isfinite(values)):
        raise ValueError("pair contrast must contain only finite values")
    if indices.ndim != 2 or indices.shape[1] != len(values):
        raise ValueError("bootstrap indexes must have one column per pair")
    if not np.issubdtype(indices.dtype, np.integer):
        raise ValueError("bootstrap indexes must be integers")
    if not len(indices) or np.any(indices < 0) or np.any(indices >= len(values)):
        raise ValueError("bootstrap indexes are empty or out of range")
    bootstrap_means = values[indices].mean(axis=1)
    low = float(np.quantile(bootstrap_means, 0.025, method="linear"))
    high = float(np.quantile(bootstrap_means, 0.975, method="linear"))
    return {
        "pairs": int(len(values)),
        "mean": float(np.mean(values)),
        "median": float(np.median(values)),
        "positive_pair_fraction": float(np.mean(values > 0.0)),
        "zero_pair_fraction": float(np.mean(values == 0.0)),
        "mean_bootstrap_ci95_low": low,
        "mean_bootstrap_ci95_high": high,
        "mean_bootstrap_ci95_above_zero": low > 0.0,
    }


def paired_bootstrap_contrasts(
    reports: list[dict[str, Any]], *, seed: int, resamples: int
) -> dict[str, Any]:
    """Compute preregistered pair-level production-route contrasts.

    Each crossover pair remains one experimental unit: its two sides have
    already been averaged for teacher BPB and jointly scored by the symmetric
    raw-byte n-gram margin.  One bootstrap index matrix is shared across all
    six summaries so their deterministic resamples remain paired as well.
    Positive values always favor recurrent ``correct_antecedent``.
    """

    if not reports:
        raise ValueError("cannot bootstrap an empty pair report list")
    if seed < 0:
        raise ValueError("bootstrap seed must be nonnegative")
    if resamples < 100:
        raise ValueError("bootstrap resamples must be at least 100")
    pair_ids = [str(row["pair_id"]) for row in reports]
    if len(set(pair_ids)) != len(pair_ids):
        raise ValueError("pair reports must have unique pair IDs")
    reports = [
        row
        for _, row in sorted(
            zip(pair_ids, reports, strict=True), key=lambda item: item[0]
        )
    ]
    pair_ids = [str(row["pair_id"]) for row in reports]
    rng = np.random.Generator(np.random.PCG64(seed))
    indexes = rng.integers(
        0, len(reports), size=(resamples, len(reports)), dtype=np.int64
    )
    pair_order_sha256 = hashlib.sha256(
        json.dumps(pair_ids, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    ).hexdigest()
    resample_indices_sha256 = hashlib.sha256(
        indexes.astype("<u8", copy=False).tobytes(order="C")
    ).hexdigest()

    def endpoint_values(condition: str, endpoint: str) -> np.ndarray:
        values = np.asarray(
            [row["condition_endpoints"][condition][endpoint] for row in reports],
            dtype=np.float64,
        )
        if not np.all(np.isfinite(values)):
            raise ValueError(f"{condition} {endpoint} contains a nonfinite value")
        return values

    correct_bpb = endpoint_values("correct_antecedent", "mean_teacher_forced_bpb")
    correct_margin = np.asarray(
        [
            row["condition_endpoints"]["correct_antecedent"]["paired_raw_byte_ngram"][
                "correct_minus_crossed_margin"
            ]
            for row in reports
        ],
        dtype=np.float64,
    )
    if not np.all(np.isfinite(correct_margin)):
        raise ValueError("correct antecedent n-gram margin contains a nonfinite value")

    contrasts: dict[str, dict[str, Any]] = {}
    gate_flags: dict[str, bool] = {}
    for label, comparator in BOOTSTRAP_CONTRASTS:
        comparator_bpb = endpoint_values(comparator, "mean_teacher_forced_bpb")
        comparator_margin = np.asarray(
            [
                row["condition_endpoints"][comparator]["paired_raw_byte_ngram"][
                    "correct_minus_crossed_margin"
                ]
                for row in reports
            ],
            dtype=np.float64,
        )
        if not np.all(np.isfinite(comparator_margin)):
            raise ValueError(f"{comparator} n-gram margin contains a nonfinite value")
        teacher = _paired_bootstrap_summary(
            comparator_bpb - correct_bpb,
            resample_indices=indexes,
        )
        free = _paired_bootstrap_summary(
            correct_margin - comparator_margin,
            resample_indices=indexes,
        )
        teacher_gate = bool(teacher["mean_bootstrap_ci95_above_zero"])
        free_gate = bool(free["mean_bootstrap_ci95_above_zero"])
        contrasts[label] = {
            "comparator_condition": comparator,
            "teacher_forced_bpb_advantage": teacher,
            "free_paired_raw_byte_ngram_margin_advantage": free,
            "both_ci95_above_zero": teacher_gate and free_gate,
        }
        gate_flags[f"{label}_teacher_bpb_ci95_above_zero"] = teacher_gate
        gate_flags[f"{label}_free_ngram_ci95_above_zero"] = free_gate

    return {
        "method": "paired nonparametric percentile bootstrap over crossover pairs",
        "experimental_unit": (
            "one crossover pair; teacher BPB is side-averaged and the free "
            "raw-byte n-gram margin is already symmetric across both sides"
        ),
        "seed": int(seed),
        "resamples": int(resamples),
        "rng": "numpy.random.PCG64",
        "quantile_method": "linear",
        "canonical_pair_order": "lexicographic pair_id",
        "pair_order_sha256": pair_order_sha256,
        "resample_indices_sha256": resample_indices_sha256,
        "shared_resample_indices_across_all_contrasts": True,
        "positive_direction": {
            "teacher_forced_bpb_advantage": "comparator BPB minus correct BPB",
            "free_paired_raw_byte_ngram_margin_advantage": (
                "correct margin minus comparator margin"
            ),
        },
        "contrasts": contrasts,
        "preregistered_gates": {
            **gate_flags,
            "all_six_ci95_above_zero": all(gate_flags.values()),
        },
    }


def _selection_value(value: float | None) -> float:
    return -float("inf") if value is None else float(value)


def beta_selection_rank(
    aggregate: dict[str, dict[str, Any]], beta: float
) -> tuple[float, ...]:
    """Predeclared free-output-first development rank; smaller beta wins ties."""

    causal = aggregate["correct_antecedent"]
    prefix = causal["exact_reference_prefix_rates"]
    ngram = causal["paired_raw_byte_ngram_correct_minus_crossed"]
    return (
        _selection_value(prefix["horizon"]["exact_fraction"]),
        _selection_value(prefix["32"]["exact_fraction"]),
        _selection_value(prefix["16"]["exact_fraction"]),
        _selection_value(prefix["8"]["exact_fraction"]),
        float(ngram["mean_margin"]),
        float(causal["mean_teacher_forced_bpb_improvement_vs_native"]),
        -float(beta),
    )


def _pair_report(
    base_cortex: FrozenCortex,
    route_cortex: FrozenCortex,
    pair: AntecedentCrossoverPair,
    *,
    beta: float,
    max_new_bytes: int,
    minimum_probability: float,
    lexical_dimensions: int = 2048,
) -> dict[str, Any]:
    results: dict[str, dict[str, SideConditionResult]] = {}
    for condition in CONDITION_NAMES:
        results[condition] = {
            side: evaluate_side_condition(
                base_cortex,
                route_cortex,
                pair,
                side=side,
                condition=condition,
                beta=beta,
                max_new_bytes=max_new_bytes,
                minimum_probability=minimum_probability,
            )
            for side in ("a", "b")
        }
    native = results["native_base"]
    disconnected = results["disconnected_correct_antecedent"]
    sham = results["duplicate_current_state_sham"]
    disconnected_teacher_exact = all(
        np.array_equal(
            native[side].teacher_forced.combined_distributions,
            disconnected[side].teacher_forced.combined_distributions,
        )
        for side in ("a", "b")
    )
    disconnected_greedy_exact = all(
        native[side].greedy.observed == disconnected[side].greedy.observed
        and np.array_equal(
            native[side].greedy.combined_distributions,
            disconnected[side].greedy.combined_distributions,
        )
        for side in ("a", "b")
    )
    sham_teacher_exact = all(
        np.array_equal(
            native[side].teacher_forced.combined_distributions,
            sham[side].teacher_forced.combined_distributions,
        )
        for side in ("a", "b")
    )
    sham_greedy_exact = all(
        native[side].greedy.observed == sham[side].greedy.observed
        and np.array_equal(
            native[side].greedy.combined_distributions,
            sham[side].greedy.combined_distributions,
        )
        for side in ("a", "b")
    )
    endpoints = {
        condition: _condition_pair_endpoints(
            by_side, pair, lexical_dimensions=lexical_dimensions
        )
        for condition, by_side in results.items()
    }
    return {
        "pair_id": pair.pair_id,
        "provenance": {
            "route_prime_kind": "schema_v4_audit_subranges.original_prefix",
            "original_prefix_sha256_a": hashlib.sha256(
                pair.original_prefix_a
            ).hexdigest(),
            "original_prefix_sha256_b": hashlib.sha256(
                pair.original_prefix_b
            ).hexdigest(),
            "common_suffix_bytes_excluded_from_correct_route": (
                pair.common_suffix_bytes
            ),
            "response_or_future_bytes_used_to_prime_route": False,
        },
        "conditions": {
            condition: {
                side: _side_report(
                    side_result,
                    pair.response_a if side == "a" else pair.response_b,
                )
                for side, side_result in by_side.items()
            }
            for condition, by_side in results.items()
        },
        "condition_endpoints": endpoints,
        "protocol_invariants": {
            "beta_zero_teacher_forced_trace_exact": disconnected_teacher_exact,
            "beta_zero_greedy_trace_and_output_exact": disconnected_greedy_exact,
            "duplicate_current_teacher_forced_trace_exact": sham_teacher_exact,
            "duplicate_current_greedy_trace_and_output_exact": sham_greedy_exact,
            "correct_swapped_disconnected_and_sham_compute_matched": True,
        },
    }


def _resolve_beta_values(args: argparse.Namespace) -> tuple[tuple[float, ...], bool]:
    fixed = getattr(args, "beta", None)
    requested_grid = getattr(args, "beta_values", None)
    if args.split == "test":
        if requested_grid:
            raise ValueError("test invocation cannot sweep or select beta")
        if fixed is None:
            raise ValueError("test invocation requires one frozen --beta")
        values = (float(fixed),)
        selection = False
    elif fixed is not None and requested_grid:
        raise ValueError("choose fixed --beta or --beta-values, not both")
    elif fixed is not None:
        values = (float(fixed),)
        selection = False
    else:
        values = tuple(
            float(value)
            for value in (
                requested_grid if requested_grid else (0.0, 0.25, 0.5, 0.75, 1.0)
            )
        )
        selection = True
    if not values or any(not 0.0 <= value <= 1.0 for value in values):
        raise ValueError("every beta must lie in [0, 1]")
    if len(set(values)) != len(values):
        raise ValueError("beta values must be unique")
    return values, selection


def run_ablation(args: argparse.Namespace) -> dict[str, Any]:
    """Run a dev beta sweep or one explicitly frozen test-beta assay."""

    if args.split == "test" and not args.allow_test:
        raise ValueError("refusing to open test split without --allow-test")
    beta_values, selection_performed = _resolve_beta_values(args)
    confirmatory_gate_eligible = (
        args.split == "test" and not selection_performed and len(beta_values) == 1
    )
    if args.max_new_bytes < 1:
        raise ValueError("max_new_bytes must be positive")
    lexical_dimensions = int(getattr(args, "lexical_dimensions", 2048))
    if lexical_dimensions < 16:
        raise ValueError("lexical_dimensions must be at least sixteen")
    bootstrap_seed = int(getattr(args, "bootstrap_seed", 260_916))
    bootstrap_resamples = int(getattr(args, "bootstrap_resamples", 4_000))
    if bootstrap_seed < 0:
        raise ValueError("bootstrap seed must be nonnegative")
    if bootstrap_resamples < 100:
        raise ValueError("bootstrap resamples must be at least 100")
    pairs = load_antecedent_pairs(args.dataset_dir, args.split)
    if args.max_pairs is not None:
        if args.max_pairs < 1:
            raise ValueError("max_pairs must be positive")
        pairs = pairs[: args.max_pairs]

    # Importing and loading are intentionally after the split firewall.
    from manifoldflow.experiments import (
        dendritic_basin_shared_goal_crossover_ablation as crossover,
    )

    base_cortex = crossover._load_native(args.checkpoint)
    route_cortex = crossover._load_native(args.checkpoint)
    if base_cortex is None or route_cortex is None:
        raise ValueError("a frozen native checkpoint is required")
    beta_runs = []
    for beta in beta_values:
        pair_reports = [
            _pair_report(
                base_cortex,
                route_cortex,
                pair,
                beta=beta,
                max_new_bytes=args.max_new_bytes,
                minimum_probability=args.minimum_probability,
                lexical_dimensions=lexical_dimensions,
            )
            for pair in pairs
        ]
        aggregate = aggregate_pair_reports(pair_reports)
        bootstrap = paired_bootstrap_contrasts(
            pair_reports,
            seed=bootstrap_seed,
            resamples=bootstrap_resamples,
        )
        bootstrap["gate_scope"] = {
            "confirmatory_eligible": confirmatory_gate_eligible,
            "scope": (
                "confirmatory_frozen_test"
                if confirmatory_gate_eligible
                else "exploratory_development_or_diagnostic"
            ),
            "note": (
                "CI flags support a confirmatory gate only for an explicitly "
                "authorized test invocation with one beta frozen before access"
            ),
        }
        valid = all(
            all(bool(value) for value in row["protocol_invariants"].values())
            for row in pair_reports
        )
        beta_runs.append(
            {
                "beta": beta,
                "aggregate": aggregate,
                "paired_bootstrap": bootstrap,
                "protocol_valid": valid,
                "pair_reports": pair_reports,
            }
        )
    selected_run = max(
        beta_runs,
        key=lambda row: beta_selection_rank(row["aggregate"], row["beta"]),
    )
    protocol_valid = all(bool(row["protocol_valid"]) for row in beta_runs)
    return {
        "schema_version": 1,
        "experiment": "frozen_native_dual_state_antecedent_production",
        "status": "complete" if protocol_valid else "invalid_protocol_invariant",
        "config": {
            "dataset_dir": str(args.dataset_dir),
            "checkpoint": str(args.checkpoint),
            "split": args.split,
            "selected_beta": selected_run["beta"],
            "beta_values_evaluated": list(beta_values),
            "max_new_bytes": args.max_new_bytes,
            "lexical_dimensions": lexical_dimensions,
            "minimum_probability": args.minimum_probability,
            "bootstrap_seed": bootstrap_seed,
            "bootstrap_resamples": bootstrap_resamples,
            "pairs": len(pairs),
        },
        "beta_protocol": {
            "selection_performed": selection_performed,
            "selection_split": "dev" if selection_performed else None,
            "test_beta_frozen_without_selection": args.split == "test",
            "rank_order": [
                "correct exact horizon",
                "correct exact prefix 32",
                "correct exact prefix 16",
                "correct exact prefix 8",
                "correct paired raw-byte ngram margin",
                "correct teacher-forced BPB improvement vs native",
                "smaller beta",
            ],
            "curve": {
                str(row["beta"]): {
                    "protocol_valid": row["protocol_valid"],
                    "aggregate": row["aggregate"],
                    "paired_bootstrap": row["paired_bootstrap"],
                }
                for row in beta_runs
            },
        },
        "oracle_antecedent_definition": (
            "the matching schema-v4 audit_subranges.original_prefix byte span, "
            "ending before the common interruption bridge; it is selected by "
            "evaluation metadata but contains no withheld response or future target"
        ),
        "mechanism": (
            "two recurrent states of the same frozen native cortex; normalized "
            "base^(1-beta)*route^beta prediction; shared emitted-byte feedback"
        ),
        "frozen_native_protocol": {
            "learn": False,
            "episodic_layer_enabled": False,
            "inference_adaptation_frozen": True,
            "reset_and_replay_before_every_trace": True,
            "test_split_requires_explicit_allow_test": True,
        },
        "compute_accounting": {
            "native_base_predictions_per_step": 1,
            "every_dual_condition_predictions_per_step": 2,
            "every_dual_condition_product_combines_per_step": 1,
            "active_swapped_disconnected_and_sham_state_advances_per_step": 2,
            "static_query_state_advances_per_step": 1,
            "correct_swapped_disconnected_and_sham_are_compute_matched": True,
            "note": (
                "the evaluator loads two checkpoint copies; a deployable route "
                "would share immutable anatomy and duplicate recurrent state only"
            ),
        },
        "claim_limits": [
            (
                "Correct-prefix selection is an evaluation-only oracle address; "
                "this experiment does not learn which antecedent to select."
            ),
            (
                "The route is conditioned by causal raw bytes, not a learned "
                "role-sensitive assembly interface."
            ),
            (
                "A teacher-forced improvement without a free-generation improvement "
                "does not pass the production-route hypothesis."
            ),
            (
                "Loading two copies is experimental RAM overhead and cannot be "
                "counted as a <=500 MB deployed organism without shared anatomy."
            ),
        ],
        "selected_aggregate": selected_run["aggregate"],
        "selected_paired_bootstrap": selected_run["paired_bootstrap"],
        "pairs": selected_run["pair_reports"],
    }


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset-dir", type=Path, required=True)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--split", choices=("dev", "test"), default="dev")
    parser.add_argument("--allow-test", action="store_true")
    parser.add_argument(
        "--beta",
        type=float,
        help="one fixed beta; required for test and never selected on test",
    )
    parser.add_argument(
        "--beta-values",
        type=float,
        nargs="+",
        help="development-only beta sweep (default: 0,.25,.5,.75,1)",
    )
    parser.add_argument("--max-new-bytes", type=int, default=96)
    parser.add_argument("--max-pairs", type=int)
    parser.add_argument("--lexical-dimensions", type=int, default=2048)
    parser.add_argument("--minimum-probability", type=float, default=1e-300)
    parser.add_argument("--bootstrap-seed", type=int, default=260_916)
    parser.add_argument("--bootstrap-resamples", type=int, default=4_000)
    return parser


def main() -> None:
    args = _parser().parse_args()
    report = run_ablation(args)
    payload = json.dumps(report, indent=2, sort_keys=True) + "\n"
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(payload, encoding="utf-8")
    print(payload, end="")


if __name__ == "__main__":
    main()
