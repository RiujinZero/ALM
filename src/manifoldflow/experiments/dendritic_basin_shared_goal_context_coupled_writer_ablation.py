"""Train and assay a context-coupled byte-production receiver.

This experiment is a downstream receiver/interface assay.  It asks whether a
continuous, self-supervised future-successor representation can alter a frozen
native cortex's byte production through learned conjunctions between a state
held across an answer and the writer's evolving output suffix.  It does *not*
assign value to coarse actions, represent a desired outcome, or establish
goal-directedness.

The chat-specific corpus adapter is inherited from the exact-crossover shared
goal experiments.  The production mechanism itself is modality-neutral: a
caller supplies a fixed-width set of integer state-feature IDs and a stream of
integer output symbols.  Here, a deterministic top-|value| coordinate/sign
code converts continuous successor vectors to sparse IDs, and raw bytes are
the output symbols.

Four allocation-matched writers are trained on exactly the same observed
response bytes, always starting each response with an empty local prefix:
``local``, ``additive``, active-count-matched ``additive_wide``, and
``coupled``.  Another coupled writer receives a Sattolo-shuffled oracle state
during training.  A complementary allocation-matched writer bank is trained
directly on the causal antecedent-evidence vector, without a future-target
predictor, including its own shuffled-mapping control.  At inference a bounded
likelihood ratio ``q_arm / q_local`` corrects the frozen native distribution.
Teacher-forced BPB and deterministic greedy generation use the same correction;
generated bytes advance both the native state and the writer suffix, never any
weights.

The CLI has a hard split firewall.  Development selection is permitted only
for the full locked pair set, input hashes, beta grid, and inferential config;
smokes remain diagnostic.  Test data is not opened unless ``--allow-test`` is
supplied, exactly one fixed beta is given, all locked inputs/configs match, and
a separate source-hashed amendment and external development-result lock both
validate before pair access.
"""

