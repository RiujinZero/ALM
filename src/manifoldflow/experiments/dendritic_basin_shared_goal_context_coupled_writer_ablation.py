def top_signed_feature_ids(vector: Any, count: int) -> tuple[int, ...]:
    """Return stable top-|value| coordinate/sign IDs.

    Magnitude is used only to choose coordinates.  Ties are broken by the
    original coordinate, and zero is assigned the non-negative sign.  Thus no
    platform-dependent sort stability or floating payload enters the writer.
    """

    values = np.asarray(vector, dtype=np.float64)
    if values.ndim != 1 or not len(values):
        raise ValueError("continuous state must be a nonempty vector")
    if not np.all(np.isfinite(values)):
        raise ValueError("continuous state must contain only finite values")
    width = int(count)
    if width < 1 or width > len(values):
        raise ValueError("state feature count must be in [1, vector width]")
    coordinates = np.arange(len(values), dtype=np.int64)
    order = np.lexsort((coordinates, -np.abs(values)))[:width]
    return tuple(2 * int(index) + int(values[index] < 0.0) for index in order.tolist())


def sattolo_indices(count: int, seed: int) -> np.ndarray:
    """Return a deterministic permutation with no fixed point."""

    if count < 2:
        raise ValueError("a no-self shuffle requires at least two episodes")
    if seed < 0:
        raise ValueError("shuffle seed must be nonnegative")
    permutation = np.arange(count, dtype=np.int64)
    rng = np.random.Generator(np.random.PCG64(seed))
    for index in range(count - 1, 0, -1):
        other = int(rng.integers(0, index))
        permutation[index], permutation[other] = (
            permutation[other],
            permutation[index],
        )
    if np.any(permutation == np.arange(count)):
        raise AssertionError("Sattolo permutation unexpectedly has a fixed point")
    return permutation


def _training_arrays(
    examples: Sequence[TrainingExample], feature_dimensions: int
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    full = np.asarray([row.evidence for row in examples], dtype=np.float64)
    targets = np.asarray([row.goal_target_vector for row in examples], dtype=np.float64)
    if full.ndim != 2 or targets.ndim != 2:
        raise ValueError("training evidence and successor targets must be rectangular")
    if len(full) < 2 or len(full) != len(targets):
        raise ValueError("training evidence and targets need matching episode rows")
    if feature_dimensions < 1 or full.shape[1] < feature_dimensions:
        raise ValueError("pending-event width exceeds causal evidence width")
    if not np.all(np.isfinite(full)) or not np.all(np.isfinite(targets)):
        raise ValueError("training evidence and targets must be finite")
    return full, full[:, :feature_dimensions], targets


def _responses_digest(examples: Sequence[TrainingExample], epochs: int) -> str:
    digest = hashlib.sha256()
    for _ in range(epochs):
        for row in examples:
            digest.update(len(row.response).to_bytes(8, "little"))
            digest.update(row.response)
    return digest.hexdigest()


def fit_context_coupled_mechanism(
    examples: list[TrainingExample],
    *,
    feature_dimensions: int,
    ridge_alpha: float,
    state_feature_count: int,
    table_bits: int,
    learning_rate: float,
    local_orders: tuple[int, ...],
    training_epochs: int,
    control_seed: int,
) -> ContextCoupledMechanism:
    """Fit causal state predictors and all production/control writers."""

    if training_epochs < 1:
        raise ValueError("training epochs must be positive")
    full, pending, targets = _training_arrays(examples, feature_dimensions)
    if state_feature_count > targets.shape[1]:
        raise ValueError("state feature count exceeds successor target width")
    if state_feature_count > feature_dimensions:
        raise ValueError("state feature count exceeds pending-event width")
    if any(not row.response for row in examples):
        raise ValueError("training response windows must be nonempty")

    full_predictor = fit_ridge(full, targets, ridge_alpha)
    pending_predictor = fit_ridge(pending, targets, ridge_alpha)
    states = [top_signed_feature_ids(row, state_feature_count) for row in targets]
    antecedent_states = [
        top_signed_feature_ids(row, state_feature_count) for row in full
    ]
    permutation = sattolo_indices(len(examples), control_seed + 211)
    antecedent_permutation = sattolo_indices(len(examples), control_seed + 311)
    shuffled_state_id_equalities = sum(
        states[index] == states[int(permutation[index])] for index in range(len(states))
    )
    antecedent_shuffled_state_id_equalities = sum(
        antecedent_states[index]
        == antecedent_states[int(antecedent_permutation[index])]
        for index in range(len(antecedent_states))
    )

    def new_writer(kind: str) -> ContextCoupledByteWriter:
        return ContextCoupledByteWriter(
            kind,  # type: ignore[arg-type]
            alphabet_size=256,
            table_bits=table_bits,
            learning_rate=learning_rate,
            local_orders=local_orders,
            max_persistent_features=state_feature_count,
        )

    writers = {name: new_writer(name) for name in WRITER_NAMES}
    shuffled_writer = new_writer("coupled")
    antecedent_writers = {
        name: new_writer(name) for name in ("additive", "additive_wide", "coupled")
    }
    antecedent_shuffled_writer = new_writer("coupled")
    for _ in range(training_epochs):
        for index, row in enumerate(examples):
            # An empty prefix is deliberate: none of the response target or
            # conversation bytes leak into the production-phase feature at t=0.
            writers["local"].fit_episode(row.response, (), prefix=b"")
            for name in ("additive", "additive_wide", "coupled"):
                writers[name].fit_episode(row.response, states[index], prefix=b"")
            shuffled_writer.fit_episode(
                row.response, states[int(permutation[index])], prefix=b""
            )
            for name in ("additive", "additive_wide", "coupled"):
                antecedent_writers[name].fit_episode(
                    row.response, antecedent_states[index], prefix=b""
                )
            antecedent_shuffled_writer.fit_episode(
                row.response,
                antecedent_states[int(antecedent_permutation[index])],
                prefix=b"",
            )

    allocations = {writer.allocated_bytes for writer in writers.values()}
    allocations.add(shuffled_writer.allocated_bytes)
    allocations.update(writer.allocated_bytes for writer in antecedent_writers.values())
    allocations.add(antecedent_shuffled_writer.allocated_bytes)
    if len(allocations) != 1:
        raise AssertionError("writer controls do not have identical allocation")
    expected_episodes = training_epochs * len(examples)
    expected_symbols = training_epochs * sum(len(row.response) for row in examples)
    for writer in (
        *writers.values(),
        shuffled_writer,
        *antecedent_writers.values(),
        antecedent_shuffled_writer,
    ):
        if writer.episodes_seen != expected_episodes:
            raise AssertionError("writer training episode counts differ")
        if writer.symbols_seen != expected_symbols:
            raise AssertionError("writer training byte counts differ")

    prior = np.mean(targets, axis=0)
    prior.flags.writeable = False
    antecedent_prior = np.mean(full, axis=0)
    antecedent_prior.flags.writeable = False
    return ContextCoupledMechanism(
        full_predictor=full_predictor,
        pending_predictor=pending_predictor,
        writers=writers,
        shuffled_training_writer=shuffled_writer,
        antecedent_writers=antecedent_writers,
        antecedent_shuffled_training_writer=antecedent_shuffled_writer,
        prior_state=prior,
        antecedent_prior_state=antecedent_prior,
        state_feature_count=state_feature_count,
        target_dimensions=int(targets.shape[1]),
        shuffled_training_permutation=permutation,
        antecedent_shuffled_training_permutation=antecedent_permutation,
        shuffled_training_effective_state_id_equalities=(shuffled_state_id_equalities),
        antecedent_shuffled_training_effective_state_id_equalities=(
            antecedent_shuffled_state_id_equalities
        ),
        training_response_sha256=_responses_digest(examples, training_epochs),
        training_epochs=training_epochs,
    )


def online_context_evidence(
    context: bytes,
    *,
    dimensions: int,
    decays: tuple[float, ...],
) -> np.ndarray:
    """Recompute pending+EMA evidence over every causal turn in ``context``.

    Unlike the pair loader's reinstated evidence, this path has no metadata
    cutoff.  It parses the complete presented context, including HOLD, bridge,
    and the final common RESUME request.  The empty trailing ASSISTANT marker is
    not an event because it has no observed content.
    """

    if dimensions < 8:
        raise ValueError("online evidence dimensions must be at least eight")
    if not decays or any(not 0.0 < value < 1.0 for value in decays):
        raise ValueError("online evidence decays must lie in (0, 1)")
    turns = parse_turns(context.decode("utf-8", errors="replace"))
    if not turns:
        raise ValueError("online context contains no parsed causal events")
    vectors = [hashed_text_vector(turn.text, dimensions) for turn in turns]
    states = [np.zeros(dimensions, dtype=np.float64) for _ in decays]
    for vector in vectors:
        for index, decay in enumerate(decays):
            states[index] = decay * states[index] + (1.0 - decay) * vector
    return np.concatenate((vectors[-1], *(normalize(state) for state in states)))


def predict_pair_states(
    pairs: list[CrossoverPair],
    mechanism: ContextCoupledMechanism,
    *,
    feature_dimensions: int,
    state_decays: tuple[float, ...],
    control_seed: int,
) -> tuple[list[PairStates], np.ndarray, dict[str, np.ndarray]]:
    """Build oracle, causal, and strict no-self shuffled evaluation states."""

    if not pairs:
        raise ValueError("evaluation requires at least one crossover pair")
    evidence = np.asarray(
        [vector for pair in pairs for vector in (pair.evidence_a, pair.evidence_b)],
        dtype=np.float64,
    )
    target_rows: list[np.ndarray] = []
    for pair in pairs:
        if pair.goal_target_vector_a is None or pair.goal_target_vector_b is None:
            raise ValueError("future-successor target vectors are required")
        target_rows.extend((pair.goal_target_vector_a, pair.goal_target_vector_b))
    targets = np.asarray(target_rows, dtype=np.float64)
    if targets.ndim != 2 or targets.shape[1] != mechanism.target_dimensions:
        raise ValueError("evaluation successor targets have an incompatible shape")
    if evidence.ndim != 2 or evidence.shape[1] < feature_dimensions:
        raise ValueError("evaluation evidence has an incompatible shape")
    if not np.all(np.isfinite(evidence)) or not np.all(np.isfinite(targets)):
        raise ValueError("evaluation evidence and targets must be finite")

    causal_full = mechanism.full_predictor.predict(evidence)
    causal_pending = mechanism.pending_predictor.predict(
        evidence[:, :feature_dimensions]
    )
    online_evidence = np.asarray(
        [
            online_context_evidence(
                context,
                dimensions=feature_dimensions,
                decays=state_decays,
            )
            for pair in pairs
            for context in (pair.context_a, pair.context_b)
        ],
        dtype=np.float64,
    )
    if online_evidence.shape != evidence.shape:
        raise ValueError("online and reinstated antecedent evidence shapes differ")
    permutation = sattolo_indices(len(evidence), control_seed)
    shuffled = causal_full[permutation]
    shuffled_antecedent = online_evidence[permutation]
    rows = [
        PairStates(
            oracle_a=targets[2 * index],
            oracle_b=targets[2 * index + 1],
            causal_full_a=causal_full[2 * index],
            causal_full_b=causal_full[2 * index + 1],
            causal_pending_a=causal_pending[2 * index],
            causal_pending_b=causal_pending[2 * index + 1],
            shuffled_causal_a=shuffled[2 * index],
            shuffled_causal_b=shuffled[2 * index + 1],
            antecedent_reinstated_a=evidence[2 * index],
            antecedent_reinstated_b=evidence[2 * index + 1],
            antecedent_online_a=online_evidence[2 * index],
            antecedent_online_b=online_evidence[2 * index + 1],
            antecedent_online_pending_a=online_evidence[2 * index, :feature_dimensions],
            antecedent_online_pending_b=online_evidence[
                2 * index + 1, :feature_dimensions
            ],
            antecedent_online_shuffled_a=shuffled_antecedent[2 * index],
            antecedent_online_shuffled_b=shuffled_antecedent[2 * index + 1],
        )
        for index in range(len(pairs))
    ]
    return (
        rows,
        permutation,
        {
            "target": targets,
            "causal_full": causal_full,
            "causal_pending_only": causal_pending,
            "shuffled_causal_episode": shuffled,
            "antecedent_reinstated": evidence,
            "antecedent_online_causal": online_evidence,
            "antecedent_online_pending_only": online_evidence[:, :feature_dimensions],
            "antecedent_online_shuffled_episode": shuffled_antecedent,
        },
    )


def writer_probability_trace(
    writer: ContextCoupledByteWriter,
    observed: bytes,
    persistent_feature_ids: Sequence[int],
    *,
    freeze_joint: bool = False,
    temperature: float = 1.0,
) -> np.ndarray:
    """Teacher-force a writer trace from an empty response-local prefix."""

    history = bytearray()
    trace = np.empty((len(observed), 256), dtype=np.float64)
    for index, byte_id in enumerate(observed):
        trace[index] = writer.distribution(
            history,
            persistent_feature_ids,
            freeze_joint=freeze_joint,
            temperature=temperature,
        )
        history.append(byte_id)
    return trace


def corrected_probability_trace(
    base: np.ndarray,
    local: np.ndarray,
    arm: np.ndarray,
    *,
    beta: float,
    log_ratio_clip: float,
) -> np.ndarray:
    """Apply the bounded route ratio row-wise with an exact zero bypass."""

    base_trace = np.asarray(base)
    if base_trace.ndim != 2 or base_trace.shape[1] != 256:
        raise ValueError("base trace must have shape (steps, 256)")
    if beta == 0.0 or np.array_equal(local, arm):
        return np.array(base_trace, copy=True)
    if (
        np.asarray(local).shape != base_trace.shape
        or np.asarray(arm).shape != base_trace.shape
    ):
        raise ValueError("writer and base traces must have identical shapes")
    return np.asarray(
        [
            likelihood_ratio_correction(
                base_row,
                local_row,
                arm_row,
                beta=beta,
                log_ratio_clip=log_ratio_clip,
            )
            for base_row, local_row, arm_row in zip(base_trace, local, arm, strict=True)
        ],
        dtype=np.float64,
    )


def _validate_native_distribution(values: Any) -> np.ndarray:
    distribution = np.asarray(values)
    if distribution.shape != (256,):
        raise ValueError("native distribution must have shape (256,)")
    if not np.all(np.isfinite(distribution)) or np.any(distribution < 0.0):
        raise ValueError("native distribution must be finite and nonnegative")
    if not np.isclose(float(distribution.sum()), 1.0, rtol=0.0, atol=1e-6):
        raise ValueError("native distribution must sum to one")
    return np.array(distribution, copy=True)


def _prime(cortex: FrozenCortex, context: bytes) -> None:
    cortex.reset_episode()
    if context:
        cortex.observe_chunk_probabilities(
            np.frombuffer(context, dtype=np.uint8), learn=False
        )


def _advance(cortex: FrozenCortex, byte_id: int) -> None:
    cortex.advance_observation(int(byte_id), learn=False)


def _target_bits(probabilities: np.ndarray, target: bytes) -> float:
    indexes = np.frombuffer(target, dtype=np.uint8)
    selected = probabilities[np.arange(len(indexes)), indexes]
    return float(np.sum(-np.log2(np.maximum(selected, 1e-300))))


def teacher_trace_from_base(
    base_trace: np.ndarray,
    target: bytes,
    local_writer: ContextCoupledByteWriter,
    arm_writer: ContextCoupledByteWriter,
    state: Sequence[int],
    *,
    beta: float,
    log_ratio_clip: float,
    freeze_joint: bool = False,
    temperature: float = 1.0,
) -> ProductionTrace:
    """Score one observed response without mutating cortex or writers."""

    if not target:
        raise ValueError("teacher-forced response must be nonempty")
    base = np.asarray(base_trace)
    if base.shape != (len(target), 256):
        raise ValueError("native base trace and response length differ")
    if beta == 0.0 or arm_writer is local_writer:
        corrected = np.array(base, copy=True)
    else:
        local = writer_probability_trace(
            local_writer, target, (), temperature=temperature
        )
        arm = writer_probability_trace(
            arm_writer,
            target,
            state,
            freeze_joint=freeze_joint,
            temperature=temperature,
        )
        corrected = corrected_probability_trace(
            base,
            local,
            arm,
            beta=beta,
            log_ratio_clip=log_ratio_clip,
        )
    return ProductionTrace(
        observed=target,
        distributions=corrected,
        target_bits=_target_bits(corrected, target),
        mode="teacher_forced",
    )


def greedy_route_trace(
    cortex: FrozenCortex,
    context: bytes,
    local_writer: ContextCoupledByteWriter,
    arm_writer: ContextCoupledByteWriter,
    state: Sequence[int],
    *,
    beta: float,
    horizon: int,
    log_ratio_clip: float,
    freeze_joint: bool = False,
    temperature: float = 1.0,
) -> ProductionTrace:
    """Greedily generate while feeding emitted bytes to both causal states."""

    if horizon < 1:
        raise ValueError("generation horizon must be positive")
    _prime(cortex, context)
    generated = bytearray()
    rows = np.empty((horizon, 256), dtype=np.float64)
    for step in range(horizon):
        base = _validate_native_distribution(cortex.predict_next_distribution())
        if beta == 0.0 or arm_writer is local_writer:
            corrected = np.array(base, copy=True)
        else:
            local = local_writer.distribution(generated, (), temperature=temperature)
            arm = arm_writer.distribution(
                generated,
                state,
                freeze_joint=freeze_joint,
                temperature=temperature,
            )
            corrected = likelihood_ratio_correction(
                base,
                local,
                arm,
                beta=beta,
                log_ratio_clip=log_ratio_clip,
            )
        byte_id = int(np.argmax(corrected))
        rows[step] = corrected
        generated.append(byte_id)
        _advance(cortex, byte_id)
    return ProductionTrace(bytes(generated), rows, None, "greedy")


def _native_greedy_trace(
    cortex: FrozenCortex, context: bytes, *, horizon: int
) -> ProductionTrace:
    if horizon < 1:
        raise ValueError("generation horizon must be positive")
    _prime(cortex, context)
    generated = bytearray()
    rows = np.empty((horizon, 256), dtype=np.float64)
    for step in range(horizon):
        distribution = _validate_native_distribution(cortex.predict_next_distribution())
        byte_id = int(np.argmax(distribution))
        rows[step] = distribution
        generated.append(byte_id)
        _advance(cortex, byte_id)
    return ProductionTrace(bytes(generated), rows, None, "greedy")


def _state_ids(
    mechanism: ContextCoupledMechanism, vector: np.ndarray
) -> tuple[int, ...]:
    return top_signed_feature_ids(vector, mechanism.state_feature_count)


def _effective_state_id_equalities(
    mechanism: ContextCoupledMechanism,
    left: np.ndarray,
    right: np.ndarray,
) -> int:
    """Count row pairs that remain equal after top-sign discretization."""

    left_rows = np.asarray(left)
    right_rows = np.asarray(right)
    if left_rows.shape != right_rows.shape or left_rows.ndim != 2:
        raise ValueError("effective state equality arrays must match and be 2-D")
    return sum(
        _state_ids(mechanism, left_row) == _state_ids(mechanism, right_row)
        for left_row, right_row in zip(left_rows, right_rows, strict=True)
    )


