def _cosine(left: np.ndarray, right: np.ndarray) -> float:
    denominator = float(np.linalg.norm(left) * np.linalg.norm(right))
    return 0.0 if denominator == 0.0 else float((left @ right) / denominator)


def representation_report(arrays: dict[str, np.ndarray]) -> dict[str, Any]:
    target = arrays["target"]
    result = {}
    for name in (
        "causal_full",
        "causal_pending_only",
        "shuffled_causal_episode",
    ):
        prediction = arrays[name]
        margins = []
        for index in range(0, len(target), 2):
            margins.append(
                _cosine(prediction[index], target[index])
                + _cosine(prediction[index + 1], target[index + 1])
                - _cosine(prediction[index], target[index + 1])
                - _cosine(prediction[index + 1], target[index])
            )
        result[name] = {
            "mean_correct_target_cosine": float(
                np.mean(
                    [
                        _cosine(prediction[index], target[index])
                        for index in range(len(target))
                    ]
                )
            ),
            "mean_symmetric_pair_margin": float(np.mean(np.asarray(margins))),
        }
    return result


def _sha256_file(path: Path) -> str:
    """Hash one provenance input without loading it into memory."""

    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _verify_manifest_payloads(
    dataset_dir: Path, manifest_path: Path, split: str
) -> dict[str, str]:
    """Verify the train and requested-split files named by the manifest."""

    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"could not read valid dataset manifest: {error}") from error
    outputs = manifest.get("outputs")
    if not isinstance(outputs, list):
        raise ValueError("dataset manifest has no output records")
    records = {str(row.get("path")): row for row in outputs if isinstance(row, dict)}
    required = (
        "train.bin",
        "train.index.jsonl",
        f"{split}_pairs.bin",
        f"{split}_pairs.jsonl",
    )
    verified: dict[str, str] = {}
    for name in required:
        record = records.get(name)
        if record is None:
            raise ValueError(f"dataset manifest omits required payload {name}")
        path = dataset_dir / name
        try:
            size = path.stat().st_size
        except OSError as error:
            raise ValueError(
                f"could not stat dataset payload {name}: {error}"
            ) from error
        if size != int(record.get("bytes", -1)):
            raise ValueError(f"dataset payload {name} byte count differs from manifest")
        digest = _sha256_file(path)
        if digest != record.get("sha256"):
            raise ValueError(f"dataset payload {name} SHA-256 differs from manifest")
        verified[name] = digest
    return verified


def _locked_config_deviations(
    args: argparse.Namespace, betas: tuple[float, ...]
) -> list[str]:
    """Return every departure from the inferential receiver protocol."""

    expected: dict[str, Any] = {
        "feature_dimensions": LOCKED_FEATURE_DIMENSIONS,
        "state_decays": LOCKED_STATE_DECAYS,
        "successor_gammas": LOCKED_SUCCESSOR_GAMMAS,
        "ridge_alpha": LOCKED_RIDGE_ALPHA,
        "state_feature_count": LOCKED_STATE_FEATURE_COUNT,
        "table_bits": LOCKED_TABLE_BITS,
        "learning_rate": LOCKED_LEARNING_RATE,
        "local_orders": LOCKED_LOCAL_ORDERS,
        "training_epochs": LOCKED_TRAINING_EPOCHS,
        "log_ratio_clip": LOCKED_LOG_RATIO_CLIP,
        "writer_temperature": LOCKED_WRITER_TEMPERATURE,
        "generation_horizon": LOCKED_GENERATION_HORIZON,
        "reference_dimensions": LOCKED_REFERENCE_DIMENSIONS,
        "control_seed": LOCKED_CONTROL_SEED,
        "bootstrap_seed": LOCKED_BOOTSTRAP_SEED,
        "bootstrap_resamples": LOCKED_BOOTSTRAP_RESAMPLES,
        "max_pairs": 0,
        "claim_limit_bytes": DEFAULT_CLAIM_LIMIT_BYTES,
    }
    deviations: list[str] = []
    for name, expected_value in expected.items():
        observed = getattr(args, name)
        if isinstance(expected_value, tuple):
            observed = tuple(observed)
        if observed != expected_value:
            deviations.append(f"{name}={observed!r} (locked {expected_value!r})")
    if args.split == "dev" and betas != DEFAULT_BETA_VALUES:
        deviations.append(f"beta_values={betas!r} (locked {DEFAULT_BETA_VALUES!r})")
    return deviations


def protocol_eligibility_report(
    args: argparse.Namespace,
    betas: tuple[float, ...],
    *,
    loaded_pair_count: int,
    evaluated_pair_count: int,
    dataset_manifest_sha256: str,
    checkpoint_sha256: str,
) -> dict[str, Any]:
    """State whether this run may select a beta or support confirmation."""

    deviations = _locked_config_deviations(args, betas)
    expected_pairs = LOCKED_DEV_PAIRS if args.split == "dev" else LOCKED_TEST_PAIRS
    if loaded_pair_count != expected_pairs:
        deviations.append(
            f"loaded_pair_count={loaded_pair_count} (locked {expected_pairs})"
        )
    if evaluated_pair_count != expected_pairs:
        deviations.append(
            f"evaluated_pair_count={evaluated_pair_count} (locked {expected_pairs})"
        )
    if dataset_manifest_sha256 != LOCKED_DATASET_MANIFEST_SHA256:
        deviations.append(
            "dataset_manifest_sha256="
            f"{dataset_manifest_sha256} (locked {LOCKED_DATASET_MANIFEST_SHA256})"
        )
    if checkpoint_sha256 != LOCKED_CHECKPOINT_SHA256:
        deviations.append(
            f"checkpoint_sha256={checkpoint_sha256} (locked {LOCKED_CHECKPOINT_SHA256})"
        )
    eligible = not deviations
    return {
        "eligible": eligible,
        "interpretation": (
            "eligible for the predeclared development selection rule"
            if eligible and args.split == "dev"
            else (
                "eligible fixed-beta test execution; confirmatory interpretation "
                "also requires the separately validated external test lock"
                if eligible
                else "diagnostic only; cannot select a beta or authorize test access"
            )
        ),
        "deviations": deviations,
        "locked_pair_count": expected_pairs,
        "loaded_pair_count": loaded_pair_count,
        "evaluated_pair_count": evaluated_pair_count,
        "dataset_manifest_sha256": dataset_manifest_sha256,
        "checkpoint_sha256": checkpoint_sha256,
        "locked_dataset_manifest_sha256": LOCKED_DATASET_MANIFEST_SHA256,
        "locked_checkpoint_sha256": LOCKED_CHECKPOINT_SHA256,
    }


def _validate_external_test_lock(
    path: Path | None,
    *,
    beta: float,
    dataset_manifest_sha256: str,
    checkpoint_sha256: str,
) -> dict[str, Any]:
    """Validate a preregistered beta lock before any test-pair payload is read."""

    if path is None:
        raise ValueError("test split requires --test-lock before test access")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"could not read valid external test lock: {error}") from error
    required = {
        "status": "locked_before_test_access",
        "selected_beta": beta,
        "dataset_manifest_sha256": dataset_manifest_sha256,
        "checkpoint_sha256": checkpoint_sha256,
    }
    for name, expected in required.items():
        if payload.get(name) != expected:
            raise ValueError(
                f"external test lock {name}={payload.get(name)!r}, "
                f"expected {expected!r}"
            )
    development_hash = payload.get("development_report_sha256")
    if not isinstance(development_hash, str) or len(development_hash) != 64:
        raise ValueError("external test lock requires a development report SHA-256")
    try:
        int(development_hash, 16)
    except ValueError as error:
        raise ValueError(
            "external test lock development report SHA-256 is not hexadecimal"
        ) from error
    if development_hash != LOCKED_DEVELOPMENT_REPORT_SHA256:
        raise ValueError(
            "external test lock development report differs from the "
            "source-locked preregistration amendment"
        )
    return {
        "path": str(path),
        "sha256": _sha256_file(path),
        "development_report_sha256": development_hash,
        "validated_before_test_pair_access": True,
    }


def validate_split_firewall(
    split: str, allow_test: bool, beta_values: Sequence[float]
) -> tuple[float, ...]:
    """Validate confirmatory access before any corpus/checkpoint file is opened."""

    if split not in {"dev", "test"}:
        raise ValueError("split must be 'dev' or 'test'")
    betas = tuple(float(value) for value in beta_values)
    if not betas or any(not np.isfinite(value) or value < 0.0 for value in betas):
        raise ValueError("beta values must be finite and nonnegative")
    if len(set(betas)) != len(betas):
        raise ValueError("beta values must be unique")
    if split == "test" and not allow_test:
        raise ValueError("refusing to open test split without --allow-test")
    if split == "test" and len(betas) != 1:
        raise ValueError("test split requires exactly one fixed beta")
    return betas


def _slice_pairs(pairs: list[CrossoverPair], maximum: int) -> list[CrossoverPair]:
    if maximum < 0:
        raise ValueError("maximum pair count must be nonnegative")
    return pairs if maximum == 0 else pairs[:maximum]


def beta_freeze_decision(
    split: str,
    betas: tuple[float, ...],
    beta_runs: Mapping[str, Any],
    *,
    selection_eligible: bool = True,
    ineligible_reasons: Sequence[str] = (),
) -> dict[str, Any]:
    """Select only on development; never inspect test outcomes for selection."""

    if split == "test":
        if len(betas) != 1:
            raise ValueError("test freeze reporting requires one supplied beta")
        return {
            "mode": "fixed_beta_test_no_within_run_selection",
            "supplied_beta_preselected": betas[0],
            "selection_performed": False,
            "fixed_beta_candidate_for_separate_test_run": None,
            "test_outcomes_not_used_for_beta_selection": True,
            "successor_family_excluded_from_decision": True,
            "external_preregistered_beta_lock_required_for_confirmation": True,
        }
    if split != "dev":
        raise ValueError("beta freeze decision split must be dev or test")
    if not selection_eligible:
        return {
            "mode": "development_diagnostic_ineligible_for_selection",
            "selection_performed": False,
            "ineligible_reasons": list(ineligible_reasons),
            "passing_nonzero_betas": None,
            "fixed_beta_candidate_for_separate_test_run": None,
            "test_run_permitted_by_this_development_result": False,
            "successor_family_excluded_from_decision": True,
            "beta_outcomes_not_inspected_for_selection": True,
        }
    passing = sorted(
        beta
        for beta in betas
        if beta > 0.0
        and bool(beta_runs[str(beta)]["antecedent_preoutput_gate"]["full_gate_passed"])
    )
    candidate = None if not passing else passing[0]
    return {
        "mode": "development_predeclared_gate",
        "selection_rule": (
            "smallest nonzero development beta passing every predeclared "
            "antecedent teacher-BPB and free-ngram CI gate"
        ),
        "selection_performed": True,
        "passing_nonzero_betas": passing,
        "fixed_beta_candidate_for_separate_test_run": candidate,
        "fallback_beta_when_none_pass": 0.0,
        "test_run_permitted_by_this_development_result": candidate is not None,
        "successor_family_excluded_from_decision": True,
    }


def run_ablation(args: argparse.Namespace) -> dict[str, Any]:
    """Fit on train and evaluate only the requested, firewalled split."""

    started = time.perf_counter()
    # This must remain the first operation: an invalid test request is rejected
    # before even train metadata, much less a test payload, can be opened.
    betas = validate_split_firewall(args.split, args.allow_test, args.beta_values)
    if args.split == "test" and getattr(args, "max_pairs", 0) != 0:
        raise ValueError("test split forbids --max-pairs; all 128 pairs are locked")
    if args.split == "test" and (
        LOCKED_TEST_BETA is None or LOCKED_DEVELOPMENT_REPORT_SHA256 is None
    ):
        raise ValueError(
            "test access is disabled in this development source; a separately "
            "hashed amendment must lock an eligible development report and beta"
        )
    if args.split == "test" and betas != (LOCKED_TEST_BETA,):
        raise ValueError("supplied test beta differs from the source-locked beta")
    if args.feature_dimensions < 8:
        raise ValueError("feature dimensions must be at least eight")
    if args.state_feature_count < 1:
        raise ValueError("state feature count must be positive")
    if args.generation_horizon < 1:
        raise ValueError("generation horizon must be positive")
    if args.reference_dimensions < 16:
        raise ValueError("reference dimensions must be at least sixteen")
    if args.max_pairs < 0:
        raise ValueError("maximum pair count must be nonnegative")
    if args.bootstrap_resamples < 100:
        raise ValueError("bootstrap resamples must be at least 100")
    if args.bootstrap_seed < 0 or args.control_seed < 0:
        raise ValueError("control and bootstrap seeds must be nonnegative")
    if args.claim_limit_bytes < 1:
        raise ValueError("claim limit must be positive")
    if not np.isfinite(args.log_ratio_clip) or args.log_ratio_clip <= 0.0:
        raise ValueError("log-ratio clip must be finite and positive")
    if not np.isfinite(args.writer_temperature) or args.writer_temperature <= 0.0:
        raise ValueError("writer temperature must be finite and positive")
    if not np.isfinite(args.ridge_alpha) or args.ridge_alpha <= 0.0:
        raise ValueError("ridge alpha must be finite and positive")
    if not np.isfinite(args.learning_rate) or args.learning_rate <= 0.0:
        raise ValueError("learning rate must be finite and positive")
    if args.training_epochs < 1:
        raise ValueError("training epochs must be positive")
    decays = tuple(float(value) for value in args.state_decays)
    gammas = tuple(float(value) for value in args.successor_gammas)
    if any(not 0.0 < value < 1.0 for value in (*decays, *gammas)):
        raise ValueError("state decays and successor gammas must lie in (0, 1)")

    config_deviations = _locked_config_deviations(args, betas)
    if args.split == "test" and config_deviations:
        raise ValueError(
            "test split requires the locked inferential configuration: "
            + "; ".join(config_deviations)
        )
    manifest_path = args.dataset_dir / "manifest.json"
    dataset_manifest_sha256 = _sha256_file(manifest_path)
    checkpoint_sha256 = _sha256_file(args.checkpoint)
    test_lock_report = None
    if args.split == "test":
        if dataset_manifest_sha256 != LOCKED_DATASET_MANIFEST_SHA256:
            raise ValueError("test dataset manifest does not match the locked input")
        if checkpoint_sha256 != LOCKED_CHECKPOINT_SHA256:
            raise ValueError("test checkpoint does not match the locked input")
        test_lock_report = _validate_external_test_lock(
            getattr(args, "test_lock", None),
            beta=betas[0],
            dataset_manifest_sha256=dataset_manifest_sha256,
            checkpoint_sha256=checkpoint_sha256,
        )
    dataset_payload_sha256 = _verify_manifest_payloads(
        args.dataset_dir, manifest_path, args.split
    )

    examples = load_training_examples(
        args.dataset_dir,
        dimensions=args.feature_dimensions,
        decays=decays,
        successor_gammas=gammas,
    )
    loaded_pairs = load_crossover_pairs(
        args.dataset_dir,
        args.split,
        dimensions=args.feature_dimensions,
        decays=decays,
        successor_gammas=gammas,
    )
    loaded_pair_count = len(loaded_pairs)
    pairs = _slice_pairs(loaded_pairs, args.max_pairs)
    if not pairs:
        raise ValueError("requested pair slice is empty")
    if {pair.goal_target_kind for pair in pairs} != {"successor"}:
        raise ValueError("this assay requires future-successor goal targets")
    protocol_eligibility = protocol_eligibility_report(
        args,
        betas,
        loaded_pair_count=loaded_pair_count,
        evaluated_pair_count=len(pairs),
        dataset_manifest_sha256=dataset_manifest_sha256,
        checkpoint_sha256=checkpoint_sha256,
    )
    if args.split == "test" and not protocol_eligibility["eligible"]:
        raise ValueError(
            "test run became protocol-ineligible before evaluation: "
            + "; ".join(protocol_eligibility["deviations"])
        )

    mechanism = fit_context_coupled_mechanism(
        examples,
        feature_dimensions=args.feature_dimensions,
        ridge_alpha=args.ridge_alpha,
        state_feature_count=args.state_feature_count,
        table_bits=args.table_bits,
        learning_rate=args.learning_rate,
        local_orders=tuple(int(value) for value in args.local_orders),
        training_epochs=args.training_epochs,
        control_seed=args.control_seed,
    )
