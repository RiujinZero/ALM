"""Free-generation ablation for an external shared-goal byte controller.

This is the generative follow-up to the exact crossover scoring assay.  It
fits the same future-code predictor and matched ``q0``/``qg`` byte heads, then
uses their clipped likelihood ratio to modify a frozen native cortex one byte
at a time.  Every counterfactual branch:

* resets and re-primes the cortex from the same episode context;
* advances with ``learn=False`` while episodic writes and inference adaptation
  are disabled by the shared frozen-native loader; and
* consumes the exact same precomputed uniform random draws.

Generated bytes are evaluated with an independent signed hash of raw byte
n-grams.  The paired-reference margin compares correct and crossed response
assignments, so the action head never scores its own output.  This remains a
small mechanism ablation: oracle codes see the reference by definition, while
causal and shuffled controls determine whether that upper bound transfers to
an inferred persistent state.
"""

